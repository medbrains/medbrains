#!/usr/bin/env node
// Generate src/theme/colors.generated.ts from src/theme/figma-varspec.json —
// the same spec the Figma library's variables were built from, so Figma and
// code name and resolve every colour identically (`var(--mb-…)` = Figma's WEB
// code syntax). Usage: pnpm --filter @medbrains/design-system gen:colors
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../src/theme/", import.meta.url);
const spec = JSON.parse(readFileSync(new URL("figma-varspec.json", dir), "utf8"));

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
// Figma: `surface/surfaceContainer` → `surface-container`; clinical/emergency keep their group.
const cssName = (name) => {
  const [group, role] = name.split("/");
  return group === "clinical" || group === "emergency" || group === "state"
    ? `${group}-${kebab(role)}`
    : kebab(role);
};

const prim = Object.fromEntries(spec.P);
const ramps = {};
for (const [name, hex] of spec.P) {
  const [ramp, tone] = name.split("/");
  ramps[ramp] ??= {};
  ramps[ramp][tone] = hex;
}

const roles = { light: {}, dark: {} };
const vars = { light: {}, dark: {} };
const put = (name, light, dark) => {
  const css = cssName(name);
  roles.light[camel(css)] = vars.light[`--mb-${css}`] = light;
  roles.dark[camel(css)] = vars.dark[`--mb-${css}`] = dark;
};
for (const [name, light, dark] of spec.S) put(name, prim[light], prim[dark]);
for (const [name, role, alpha] of spec.STATE) {
  const a = Math.round((alpha / 100) * 255)
    .toString(16)
    .padStart(2, "0");
  if (!roles.light[role]) throw new Error(`state ${name}: unknown role ${role}`);
  put(name, `${roles.light[role]}${a}`, `${roles.dark[role]}${a}`);
}

// Biome style: bare identifier keys, trailing commas — so the output is lint-clean as written.
const json = (o, pad = "") => {
  const inner = `${pad}  `;
  const rows = Object.entries(o).map(([k, v]) => {
    const key = /^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k);
    const val = typeof v === "object" ? json(v, inner) : JSON.stringify(v);
    return `${inner}${key}: ${val},`;
  });
  return `{\n${rows.join("\n")}\n${pad}}`;
};
const out = `// GENERATED by scripts/gen-colors.mjs from figma-varspec.json — do not edit.
// Material-3 colour roles on brand blue #0F62FE, matching the Figma library.

/** Tonal ramps (Figma "Primitives"). Not for components — use a role. */
export const ramps = ${json(ramps)} as const;

/** Colour roles per scheme (Figma "Color" / "Color Dark"), incl. clinical, emergency, state layers. */
export const roles = ${json(roles)} as const;

export type ColorRole = keyof typeof roles.light;

/** The same roles as CSS custom properties — Figma's WEB code syntax. */
export const roleCssVars = ${json(vars)} as const;
`;
writeFileSync(new URL("colors.generated.ts", dir), out);
