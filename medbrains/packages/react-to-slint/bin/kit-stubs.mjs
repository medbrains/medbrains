#!/usr/bin/env node
/**
 * Generates a stand-in for every kit component the mapping names but the kit does not draw yet,
 * so converted screens compile and can be opened while the kit is built out.
 *
 *   kit-stubs [--kit preview/kit.slint] [--out preview/stubs.slint]
 *
 * Each stand-in declares the properties and callbacks the mapping binds, and lays out its
 * children, so nothing a screen passes in is lost. A component drawn by the kit is skipped.
 */
import fs from "node:fs";
import path from "node:path";
import { loadMapping } from "../src/convert.mjs";

const HERE = path.dirname(new URL(import.meta.url).pathname);
const PREVIEW = path.resolve(HERE, "../preview");

/** Mapped targets that are callbacks, not properties. */
const CALLBACKS = new Set(["clicked", "edited", "toggled", "selected", "changed", "closed", "picked"]);
const BOOLS = new Set(["checked", "enabled", "busy", "active", "with-time"]);
const INTS = new Set(["value", "minimum", "maximum", "progress", "current-index", "total", "page", "rating"]);
const LISTS = new Set(["model", "data", "selected-values", "items"]);

/** The Slint type of one mapped property. */
function typeOf(name) {
  if (BOOLS.has(name)) return "bool";
  if (INTS.has(name)) return "int";
  if (LISTS.has(name)) return "[string]";
  return "string";
}

/** Component names a `.slint` file exports. */
function exported(file) {
  const text = fs.readFileSync(file, "utf8");
  return new Set([...text.matchAll(/export component (\w+)/g)].map((m) => m[1]));
}

export function kitStubs(mapping, drawn) {
  const wanted = new Map();
  const add = (rule) => {
    if (!rule?.slint?.startsWith("Mb") || drawn.has(rule.slint)) return;
    const props = wanted.get(rule.slint) ?? new Set();
    for (const target of Object.values(rule.props ?? {})) {
      const name = target.replace(/!$/, "");
      if (!name.startsWith("_")) props.add(name);
    }
    for (const name of Object.keys(rule.fixed ?? {})) props.add(name);
    wanted.set(rule.slint, props);
  };
  Object.values(mapping.rules).forEach(add);
  Object.values(mapping.html).forEach(add);
  add({ slint: "MbIcon", props: {} });
  const lines = [
    "// GENERATED by @medbrains/react-to-slint kit-stubs: stand-ins for kit components not drawn yet.",
    'import { Tokens } from "tokens.slint";',
    "",
  ];
  for (const [name, props] of [...wanted].sort()) {
    lines.push(`export component ${name} inherits VerticalLayout {`);
    for (const p of [...props].sort()) {
      if (["accessible-label", "accessible-description", "text"].includes(p) && p !== "text") continue;
      if (CALLBACKS.has(p)) lines.push(`    callback ${p}();`);
      else lines.push(`    in property <${typeOf(p)}> ${p};`);
    }
    lines.push("    spacing: Tokens.space-xs;", "    @children", "}", "");
  }
  return lines.join("\n");
}

function main(argv) {
  const kit = argv.includes("--kit") ? argv[argv.indexOf("--kit") + 1] : path.join(PREVIEW, "kit.slint");
  const out = argv.includes("--out") ? argv[argv.indexOf("--out") + 1] : path.join(PREVIEW, "stubs.slint");
  fs.writeFileSync(out, kitStubs(loadMapping(), exported(kit)));
  process.stdout.write(`wrote ${out}\n`);
  return 0;
}

if (path.resolve(process.argv[1] ?? "") === path.resolve(new URL(import.meta.url).pathname)) {
  process.exit(main(process.argv.slice(2)));
}
