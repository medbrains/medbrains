#!/usr/bin/env node
/**
 * Generates a runnable Slint app from a converted tree: the web app's own navigation (side
 * drawer), an app bar and a footer, and every routed page whose converted screen compiles.
 *
 *   app-shell --web apps/web/src --out <converted tree> [--ok <file listing compiling screens>]
 *
 * It reads the navigation from `config/navigation.ts`, the routes from `App.tsx` and the labels
 * from `public/locales/en/nav.json`, so the menus are the web app's, not a second copy. A
 * menu entry whose screen is not native yet stays visible, marked as web only.
 */
import fs from "node:fs";
import path from "node:path";
import { parse } from "@babel/parser";

/** The value after a flag, or null. */
const flag = (argv, name) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : null);

/** `NAV_GROUPS` as plain objects: `{ key, items: [{ key, path, children }] }`. */
function navGroups(webSrc) {
  const source = fs.readFileSync(path.join(webSrc, "config/navigation.ts"), "utf8");
  const ast = parse(source, { sourceType: "module", plugins: ["typescript", "jsx"] });
  const value = (node) => {
    if (!node) return undefined;
    if (node.type === "StringLiteral") return node.value;
    if (node.type === "ArrayExpression") return node.elements.map(value);
    if (node.type === "ObjectExpression") {
      return Object.fromEntries(node.properties.filter((p) => p.key).map((p) => [p.key.name ?? p.key.value, value(p.value)]));
    }
    if (node.type === "TSAsExpression" || node.type === "TSSatisfiesExpression") return value(node.expression);
    return undefined;
  };
  for (const st of ast.program.body) {
    const decl = (st.declaration ?? st).declarations?.[0];
    if (decl?.id?.name === "NAV_GROUPS") return value(decl.init);
  }
  throw new Error("NAV_GROUPS not found");
}

/** `route path -> { component, file }` from App.tsx's lazy imports and routes. */
function routes(webSrc) {
  const app = fs.readFileSync(path.join(webSrc, "App.tsx"), "utf8");
  const lazy = new Map();
  for (const m of app.matchAll(/const (\w+) = lazy\(\s*\(\) =>\s*import\("\.\/([^"]+)"\)\.then\(\(m\) => \(\{ default: m\.(\w+) \}\)\)/g)) {
    lazy.set(m[1], { file: m[2], component: m[3] });
  }
  const out = new Map();
  for (const m of app.matchAll(/<Route\s+path="([^"]+)"\s+element=\{\s*<(\w+)/g)) {
    // Routes inside the signed-in shell are relative ("pharmacy"); the menu uses "/pharmacy".
    const route = m[1].startsWith("/") ? m[1] : `/${m[1]}`;
    if (lazy.has(m[2]) && !out.has(route)) out.set(route, lazy.get(m[2]));
  }
  return out;
}

/** The converted `.slint` for a page import path, if it exists and exports the component. */
function screenFile(outDir, importPath, component, compiling) {
  for (const candidate of [`${importPath}.slint`, `${importPath}/index.slint`, `${importPath}/page.slint`]) {
    const file = path.join(outDir, candidate);
    if (!fs.existsSync(file) || (compiling && !compiling.has(file))) continue;
    if (new RegExp(`export component ${component}\\b`).test(fs.readFileSync(file, "utf8"))) return candidate;
  }
  return null;
}

const quote = (s) => `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const humanise = (k) => k.replace(/([a-z])([A-Z])/g, "$1 $2").replace(/^./, (c) => c.toUpperCase());

export function appShell({ webSrc, outDir, compiling }) {
  const labels = JSON.parse(fs.readFileSync(path.join(webSrc, "../public/locales/en/nav.json"), "utf8"));
  const routeMap = routes(webSrc);
  const imports = [];
  const screens = [];
  const nav = [];
  let available = 0;
  let total = 0;
  const visit = (item, depth) => {
    total += 1;
    const route = routeMap.get(item.path);
    const file = route ? screenFile(outDir, route.file, route.component, compiling) : null;
    let alias = null;
    if (file) {
      alias = `Screen${screens.length}`;
      imports.push(`import { ${route.component} as ${alias} } from ${quote(file)};`);
      screens.push({ path: item.path, alias });
      available += 1;
    }
    const label = labels[item.i18nKey] ?? humanise(item.i18nKey ?? item.path);
    nav.push(`                        NavItem { label: ${quote(label)}; route: ${quote(item.path)}; native: ${file ? "true" : "false"}; depth: ${depth}; active: root.route == ${quote(item.path)}; picked => { root.route = ${quote(item.path)}; root.page-title = ${quote(label)}; } }`);
    for (const child of item.children ?? []) visit(child, depth + 1);
  };
  for (const group of navGroups(webSrc)) {
    nav.push(`                        GroupLabel { text: ${quote(labels[`group_${group.key}`] ?? humanise(group.key))}; }`);
    for (const item of group.items ?? []) visit(item, 0);
  }
  const body = screens.map((s) => `                    if root.route == ${quote(s.path)} : ${s.alias} { }`);
  return `// GENERATED by @medbrains/react-to-slint app-shell from the web app's navigation and routes.
// ${available} of ${total} menu entries open a native screen; the rest are marked web only.
import { Palette, ScrollView } from "std-widgets.slint";
import { Tokens, Metrics, MbButton } from "@medbrains-gui-kit/kit.slint";
${imports.join("\n")}

component GroupLabel inherits Text {
    font-size: Tokens.font-xs;
    font-weight: 600;
    color: Tokens.color-content-on-surface-variant;
    height: 32px;
    vertical-alignment: bottom;
}

/** One entry in the side drawer: highlighted when open, muted when it has no native screen yet. */
component NavItem inherits Rectangle {
    in property <string> label;
    in property <string> route;
    in property <bool> native;
    in property <bool> active;
    in property <int> depth;
    callback picked();
    height: 36px;
    accessible-role: button;
    accessible-label: root.label;
    background: root.active ? Tokens.color-primary-primary-container : touch.has-hover ? Tokens.color-surface-surface-container-high : transparent;
    animate background { duration: 110ms; easing: ease-out; }
    Rectangle { x: 0; width: root.active ? 3px : 0px; background: Tokens.color-primary-primary; animate width { duration: 110ms; } }
    HorizontalLayout {
        padding-left: 12px + root.depth * 16px;
        padding-right: 8px;
        spacing: 8px;
        Text {
            text: root.label;
            font-size: Tokens.font-sm;
            color: root.native ? (root.active ? Tokens.color-primary-on-primary-container : Tokens.color-content-on-surface) : Tokens.color-content-on-surface-variant;
            vertical-alignment: center;
            overflow: elide;
            horizontal-stretch: 1;
        }
        if !root.native : Text { text: "web"; font-size: 10px; color: Tokens.color-content-on-surface-variant; vertical-alignment: center; }
    }
    touch := TouchArea { clicked => { root.picked(); } }
}

export component MedBrainsApp inherits Window {
    title: "MedBrains (native Slint preview)";
    preferred-width: 1280px;
    preferred-height: 800px;
    default-font-family: Metrics.font;
    background: Tokens.color-surface-surface;
    in-out property <string> route: ${quote(screens[0]?.path ?? "/dashboard")};
    in-out property <string> page-title: "MedBrains";
    property <bool> dark-flag: Tokens.dark;
    changed dark-flag => { Palette.color-scheme = Tokens.dark ? ColorScheme.dark : ColorScheme.light; }
    HorizontalLayout {
        Rectangle {
            width: 248px;
            background: Tokens.color-surface-surface-container-low;
            VerticalLayout {
                Rectangle {
                    height: 56px;
                    HorizontalLayout {
                        padding-left: 16px;
                        Text { text: "MedBrains"; font-size: Tokens.font-lg; font-weight: 600; color: Tokens.color-primary-primary-text; vertical-alignment: center; }
                    }
                }
                ScrollView {
                    VerticalLayout {
                        alignment: start;
                        padding-left: 8px;
                        padding-right: 8px;
                        padding-bottom: 16px;
${nav.join("\n")}
                    }
                }
            }
            Rectangle { x: parent.width - 1px; width: 1px; background: Tokens.color-outline-outline-variant; }
        }
        VerticalLayout {
            Rectangle {
                height: 56px;
                background: Tokens.color-surface-surface;
                HorizontalLayout {
                    padding-left: 24px;
                    padding-right: 16px;
                    spacing: 12px;
                    alignment: space-between;
                    Text { text: root.page-title; font-size: Tokens.font-lg; font-weight: 600; color: Tokens.color-content-on-surface; vertical-alignment: center; }
                    MbButton { text: Tokens.dark ? "Light theme" : "Dark theme"; clicked => { Tokens.dark = !Tokens.dark; } }
                }
                Rectangle { y: parent.height - 1px; height: 1px; background: Tokens.color-outline-outline-variant; }
            }
            ScrollView {
                VerticalLayout {
                    alignment: start;
                    padding: 24px;
${body.join("\n")}
                }
            }
            Rectangle {
                height: 32px;
                background: Tokens.color-surface-surface-container-low;
                HorizontalLayout {
                    padding-left: 24px;
                    padding-right: 24px;
                    alignment: space-between;
                    Text { text: "MedBrains · native Slint preview"; font-size: Tokens.font-xs; color: Tokens.color-content-on-surface-variant; vertical-alignment: center; }
                    Text { text: "${available} of ${total} screens native · data not wired yet"; font-size: Tokens.font-xs; color: Tokens.color-content-on-surface-variant; vertical-alignment: center; }
                }
            }
        }
    }
}
`;
}

function main(argv) {
  const webSrc = path.resolve(flag(argv, "--web") ?? "apps/web/src");
  const outDir = path.resolve(flag(argv, "--out") ?? ".");
  const okFile = flag(argv, "--ok");
  const compiling = okFile ? new Set(fs.readFileSync(okFile, "utf8").split("\n").filter(Boolean).map((f) => path.resolve(f))) : null;
  const text = appShell({ webSrc, outDir, compiling });
  fs.writeFileSync(path.join(outDir, "app.slint"), text);
  process.stdout.write(`${text.split("\n")[1]}\n`);
  return 0;
}

if (path.resolve(process.argv[1] ?? "") === path.resolve(new URL(import.meta.url).pathname)) {
  process.exit(main(process.argv.slice(2)));
}
