#!/usr/bin/env python3
"""The OS screen in the MedBrains colours: writes `medbrains-shell`'s GTK colour files and its mascot
from the design system's generated colours, so the shell's stylesheet never holds a colour of its own.

  os/shell-tokens.py            writes src/theme-light.css, src/theme-dark.css and assets/crab.svg
  os/shell-tokens.py --check    fails if those files differ from what the tokens give, or if any pair
                                the stylesheet draws falls short of WCAG 2.2 AA in either scheme

GTK names cannot hold a hyphen reliably, so `--mb-surface-container` becomes `@mb_surface_container`.
"""
import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SHELL = ROOT / "crates/medbrains-shell"
CRAB_SOURCE = ROOT / "apps/web/src/assets/mascot/crab-geometric.svg"
CRAB = SHELL / "assets/crab.svg"

# Each text pair `src/style.css` draws, with what it needs: 4.5 for text, 3 for large text and edges.
# The wallpaper's glows sit away from text, so text on it is checked against its neutral base.
PAIRS = [
    ("on-surface", "surface", 4.5), ("on-surface", "surface-container-lowest", 4.5),
    ("on-surface", "surface-container-low", 4.5), ("on-surface", "surface-container", 4.5),
    ("on-surface", "surface-container-high", 4.5), ("on-surface", "surface-container-highest", 4.5),
    ("on-surface-variant", "surface-container-lowest", 4.5), ("on-surface-variant", "surface-container-low", 4.5),
    ("on-surface-variant", "surface-container", 4.5), ("on-surface-variant", "surface-container-high", 4.5),
    ("primary-text", "surface-container-low", 4.5), ("primary-text", "surface-container-high", 4.5),
    ("on-primary", "primary", 4.5), ("on-tertiary", "tertiary-brand", 4.5),
    ("error", "surface-container-lowest", 4.5), ("error", "surface-container-low", 4.5),
    ("error", "surface-container-high", 4.5),
    ("primary-text", "surface-container-lowest", 3), ("outline", "surface-container", 3),
    ("primary", "surface-container-low", 3),
]


def kanidm_tokens():
    """The Kanidm token script, which already reads the generated colours and measures contrast."""
    spec = importlib.util.spec_from_file_location("kanidm_tokens", HERE / "kanidm-tokens.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def ramp(name):
    """One `Site` primitive from the generated colours, such as the pulse green."""
    text = kanidm_tokens().COLOURS.read_text()
    site = text[text.index("  Site: {"):]
    return re.search(rf"\b{name}: \"(#[0-9a-f]{{6}})\"", site).group(1)


def theme_css(scheme, values):
    """The `@define-color` file for one scheme."""
    rows = [f"/* Generated by os/shell-tokens.py from the design system, {scheme}. Do not edit. */\n"]
    # State layers carry alpha in the hex; the stylesheet makes its own with alpha() instead.
    for name, value in values.items():
        if len(value) != 7:
            continue
        rows.append(f"@define-color mb_{name[5:].replace('-', '_')} {value};\n")
    rows.append(f"@define-color mb_pulse {ramp('pulse')};\n")
    return "".join(rows)


def crab_svg(values):
    """The geometric crab with the web app's mascot colours. They are the same in both schemes."""
    colours = {
        "fill": values["--mb-primary"], "edge": values["--mb-primary"],
        "accent": values["--mb-tertiary-brand"], "ink": ramp("ink"), "eye": ramp("paper"),
    }
    svg = CRAB_SOURCE.read_text()
    # The web shows one face at a time with CSS; a still picture keeps the open eyes.
    svg = re.sub(r'<g class="(happy-e|think-d)".*?</g>', "", svg, flags=re.S)
    svg = re.sub(r"var\(--crab-([a-z]+)\)", lambda m: colours[m.group(1)], svg)
    return "<!-- Generated by os/shell-tokens.py from the web app's crab. Do not edit. -->\n" + svg


def outputs():
    """Every file this script owns, with the text it should hold."""
    found = kanidm_tokens().tokens()
    files = {SHELL / f"src/theme-{scheme}.css": theme_css(scheme, values) for scheme, values in found.items()}
    files[CRAB] = crab_svg(found["light"])
    return found, files


def main():
    """Writes the files by default; with --check, fails on drift or short contrast."""
    found, files = outputs()
    if sys.argv[1:] != ["--check"]:
        for path, text in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        return 0
    stale = [str(path.relative_to(ROOT)) for path, text in files.items()
             if not path.exists() or path.read_text() != text]
    module = kanidm_tokens()
    module.PAIRS = PAIRS
    short = module.check(found)
    if stale:
        print("STALE, run os/shell-tokens.py: " + ", ".join(stale))
    print("FAILED: " + str(short) if short else "every pair meets WCAG 2.2 AA")
    return 1 if short or stale else 0


if __name__ == "__main__":
    sys.exit(main())
