/** Escape for interpolation into the print window's HTML; null prints as a dash. */
export function esc(value: unknown): string {
  if (value == null) return "—";
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
