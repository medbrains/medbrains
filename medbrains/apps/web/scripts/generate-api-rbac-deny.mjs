/**
 * Generate Layer 1c — permission denials — for every guarded route.
 *
 * One case per route: call it as a non-bypass role that holds none of the
 * permission codes the handler requires, and expect the permission refusal —
 * a 403 whose body says `forbidden`, which is what `require_permission`
 * answers and what neither a step-up demand nor a CSRF failure says. The
 * denying role is chosen at run time from the live role table, exactly as
 * `rbac/role-blocking.spec.ts` does, so a role change rebalances the suite
 * on the next run.
 *
 * Input: apps/web/e2e/generated/rbac-routes.json from
 * scripts/emit_rbac_routes.py. Output: apps/web/e2e/rbac/generated/
 * <module>.rbac.spec.ts (gitignored), which the coverage ledger counts as
 * api.perm because it lives under rbac/. Run: `make e2e-rbac-generate`.
 *
 * Bodies: a write needs a body that deserialises, or Axum answers 422 before
 * the permission check runs. The smoke fixture when one exists, otherwise a
 * body synthesised from the handler's request struct; a route whose struct
 * needs a fixture the generator cannot make gets no case rather than a
 * false one.
 */

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  moduleOf,
  parseSeedMap,
  parseSkipEndpoints,
  parseSmokeBodies,
  routeSourceFiles,
  substituteParams,
} from "./generate-api-smoke.mjs";
import {
  indexSources,
  jsonBodyType,
  parseWriteRoutes,
  pick,
  rustSources,
  structFields,
  synthesiseBody,
} from "./generate-api-writes.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROUTES_JSON = resolve(__dirname, "../e2e/generated/rbac-routes.json");
const OUTPUT_DIR = resolve(__dirname, "../e2e/rbac/generated");

/** Body for a write route, or null when none can be made to deserialise. */
function bodyFor(route, handlers, index, seedData, smokeKeys) {
  if (route.method === "GET" || route.method === "DELETE") return {};
  if (smokeKeys.has(`${route.method} ${route.path}`)) return "smoke";
  const reg = handlers.get(`${route.method} ${route.path}`);
  if (!reg) return null;
  const fn = pick(index.fns.get(reg.handler), reg.src);
  if (!fn) return null;
  const ty = jsonBodyType(fn);
  if (ty === null) return {};
  if (ty === "Value") return {};
  const st = pick(index.structs.get(ty), fn.src);
  const fields = st ? structFields(st) : null;
  return fields ? synthesiseBody(fields, seedData, { deserialiseOnly: true }) : null;
}

function specForModule(moduleName, cases) {
  const items = cases
    .map((c) => `    ${JSON.stringify({ method: c.method, path: c.path, pattern: c.pattern, codes: c.codes, body: c.body })},`)
    .join("\n");
  return `// AUTO-GENERATED by apps/web/scripts/generate-api-rbac-deny.mjs — DO NOT EDIT.
// Regenerate with \`make e2e-rbac-generate\`.
import { readFileSync } from "node:fs";
import { expect, request as playwrightRequest, test } from "@playwright/test";
import { E2E_BACKEND_URL, loginAsRoleApi } from "../../helpers/api";
import { E2E_ROLE_DEFINITIONS, getE2EIdentity, loginForSession } from "../../helpers/e2e-identities";
import type { AuthContext } from "../../helpers/types";
import { SMOKE_BODIES } from "../../smoke/fixtures";

interface DenyCase {
  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  path: string;
  pattern: string;
  /** Every code the handler may ask for; the denying role holds none. */
  codes: string[];
  body: Record<string, unknown> | "smoke";
}

const cases: DenyCase[] = [
${items}
];

const knownFailures: Record<string, string> =
  JSON.parse(readFileSync(new URL("../../smoke/_known_failures.json", import.meta.url), "utf8")).endpoints ?? {};

const NON_BYPASS = E2E_ROLE_DEFINITIONS.filter((r) => !r.bypass).map((r) => r.role);
let ROLE_PERMS = new Map<string, Set<string>>();
const sessions = new Map<string, AuthContext>();

// The server allows 600 requests a minute per client, 30 for reports,
// analytics, print data and exports. Stay under both.
let lastGeneral = 0;
let lastHeavy = 0;
async function pace(path: string) {
  const heavy = /^\\/api\\/(reports|analytics|print-data)|\\/export/.test(path);
  const gap = heavy ? 2_100 : 110;
  const last = heavy ? lastHeavy : lastGeneral;
  const wait = last + gap - Date.now();
  if (wait > 0) await new Promise((r) => setTimeout(r, wait));
  if (heavy) lastHeavy = Date.now();
  else lastGeneral = Date.now();
}

test.describe("rbac deny ${moduleName}", () => {
  test.beforeAll(async ({ playwright }) => {
    const request = await playwright.request.newContext({ ignoreHTTPSErrors: true });
    const admin = getE2EIdentity("super_admin");
    const session = await loginForSession(request, admin.username, admin.password);
    const resp = await request.fetch(\`\${E2E_BACKEND_URL}/api/setup/roles\`, {
      headers: { cookie: session.cookieHeader, "x-csrf-token": session.csrf },
    });
    expect(resp.status(), "fetch roles").toBe(200);
    const roles: Array<{ code: string; permissions: string[] }> = await resp.json();
    ROLE_PERMS = new Map(roles.map((r) => [r.code, new Set(r.permissions)]));
  });

  test.afterAll(async () => {
    for (const ctx of sessions.values()) await ctx.request.dispose();
  });

  async function denier(codes: string[]) {
    const role = NON_BYPASS.find((r) => !codes.some((c) => ROLE_PERMS.get(r)?.has(c)));
    if (!role) return undefined;
    let ctx = sessions.get(role);
    if (!ctx) {
      const request = await playwrightRequest.newContext({ ignoreHTTPSErrors: true });
      ctx = await loginAsRoleApi(request, role);
      sessions.set(role, ctx);
    }
    return { role, ctx };
  }

  for (const c of cases) {
    test(\`\${c.method} \${c.pattern} refuses a role lacking \${c.codes.join(" | ")}\`, async () => {
      const reason = knownFailures[\`RBACDENY \${c.method} \${c.pattern}\`];
      test.skip(!!reason, \`known failure: \${reason}\`);
      const who = await denier(c.codes);
      test.skip(!who, \`every non-bypass role holds one of \${c.codes.join(" | ")}\`);
      if (!who) return;

      await pace(c.path);
      const body = c.body === "smoke" ? (SMOKE_BODIES[\`\${c.method} \${c.pattern}\`] ?? {}) : c.body;
      const init: { method: string; headers: Record<string, string>; data?: string } = {
        method: c.method,
        headers: { cookie: who.ctx.cookieHeader, "x-csrf-token": who.ctx.csrfToken },
      };
      if (c.method !== "GET" && c.method !== "DELETE") {
        init.headers["content-type"] = "application/json";
        init.data = JSON.stringify(body);
      }
      const resp = await who.ctx.request.fetch(\`\${E2E_BACKEND_URL}\${c.path}\`, init);
      const status = resp.status();
      expect(status, \`\${who.role} on \${c.method} \${c.path} must be refused\`).toBe(403);
      const answer = (await resp.json().catch(() => ({}))) as { error?: string };
      expect(answer.error, "a permission refusal, not a step-up demand").toBe("forbidden");
    });
  }
});
`;
}

function main() {
  if (!existsSync(ROUTES_JSON)) {
    console.error(`missing ${ROUTES_JSON} — run scripts/emit_rbac_routes.py first`);
    process.exit(1);
  }
  const routes = JSON.parse(readFileSync(ROUTES_JSON, "utf8"));
  const seedData = parseSeedMap();
  const smokeKeys = parseSmokeBodies();
  const skipSet = parseSkipEndpoints();
  const sources = rustSources();
  const index = indexSources(sources);
  const byFile = new Map(sources.map((s) => [s.file, s]));
  const handlers = new Map();
  for (const file of routeSourceFiles()) {
    const src = byFile.get(file);
    for (const r of parseWriteRoutes(src)) {
      const key = `${r.method} ${r.path}`;
      if (!handlers.has(key)) handlers.set(key, { ...r, src });
    }
  }

  const moduleSpecs = new Map();
  let noBody = 0;
  let skipped = 0;
  for (const route of routes) {
    if (skipSet.has(`${route.method} ${route.path}`)) {
      skipped += 1;
      continue;
    }
    const body = bodyFor(route, handlers, index, seedData, smokeKeys);
    if (body === null) {
      noBody += 1;
      continue;
    }
    const mod = moduleOf(route.path);
    if (!moduleSpecs.has(mod)) moduleSpecs.set(mod, []);
    moduleSpecs.get(mod).push({
      method: route.method,
      pattern: route.path,
      path: substituteParams(route.path, seedData),
      codes: route.codes,
      body,
    });
  }

  if (existsSync(OUTPUT_DIR)) rmSync(OUTPUT_DIR, { recursive: true });
  mkdirSync(OUTPUT_DIR, { recursive: true });
  let total = 0;
  for (const [mod, cases] of moduleSpecs) {
    cases.sort((a, b) => `${a.pattern} ${a.method}`.localeCompare(`${b.pattern} ${b.method}`));
    writeFileSync(resolve(OUTPUT_DIR, `${mod}.rbac.spec.ts`), specForModule(mod, cases));
    total += cases.length;
  }
  console.log(
    `rbac deny: ${total} cases in ${moduleSpecs.size} specs → ${OUTPUT_DIR}  (no deserialisable body: ${noBody}, skiplist: ${skipped})`,
  );
}

main();
