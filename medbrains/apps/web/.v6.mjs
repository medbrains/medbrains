import { chromium } from "playwright";
import fs from "node:fs";
const d = Object.fromEntries(fs.readFileSync("/tmp/mb-demo-login.txt","utf8").trim().split("\n").map(l=>l.split(": ")));
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 1100 }, colorScheme: "light" });
const p = await ctx.newPage();
await p.request.post("http://127.0.0.1:5191/api/auth/login", { data: { username: d.username, password: d.password, hospital_code: d["hospital code"] }, timeout: 300000 });
await p.goto("http://127.0.0.1:5191/assistant", { waitUntil: "load" });
await p.waitForTimeout(4000);
await p.getByRole("button", { name: /new chat/i }).first().click().catch(()=>{});
await p.getByRole("textbox").first().fill(process.argv[2]);
await p.keyboard.press("Enter");
await p.waitForTimeout(40000);
const steps = p.getByRole("button", { name: /Looked up/ }).last();
if (await steps.count()) await steps.click();
await p.waitForTimeout(800);
const t = await p.locator("main").innerText();
console.log(t.slice(t.lastIndexOf(process.argv[2])).slice(0, 2500));
await p.screenshot({ path: "/tmp/mb-shots/v6-query.png", fullPage: true });
await b.close();
