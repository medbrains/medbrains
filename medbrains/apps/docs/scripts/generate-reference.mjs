// Writes the generated reference pages before every build:
// - docs/developer/reference/api.md from docs/openapi.json (scripts/generate_openapi.py)
// - docs/developer/reference/env-vars.md from the crates' env reads and .env.example
// Both are gitignored: the source of truth is the code, so they cannot drift.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("../../..", import.meta.url).pathname; // medbrains/
const OUT = new URL("../docs/developer/reference/", import.meta.url).pathname;
const SECRET = /(SECRET|PASSWORD|PRIVATE_KEY|TOKEN|API_KEY|ACCESS_KEY|_KEY$|DSN|SALT|PEPPER)/;
// ponytail: regex over source, not a Rust parser; catches env::var("X") and the env_* helpers.
const READ = /\b(?:var|var_os|env_str|env_or|env_bytes|env_u64|env_usize|env_bool|env_parse)\w*\(\s*"([A-Z][A-Z0-9_]{2,})"/g;

/** One generated page: front matter, a warning not to hand-edit, the body. */
function page(file, title, description, body) {
  const head = `---\ntitle: ${title}\ndescription: ${JSON.stringify(description)}\n---\n\n`;
  const note = "<!-- Generated by apps/docs/scripts/generate-reference.mjs. Do not edit. -->\n\n";
  writeFileSync(join(OUT, file), head + note + body);
}

/** Every .rs file under a directory, skipping build output. */
function rustFiles(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    if (name === "target" || name === "node_modules" || name.startsWith(".")) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) rustFiles(p, acc);
    else if (name.endsWith(".rs")) acc.push(p);
  }
  return acc;
}

/** The API reference: one table per tag, method, path and permission. */
function apiReference() {
  const spec = JSON.parse(readFileSync(join(ROOT, "docs/openapi.json"), "utf8"));
  const byTag = new Map();
  for (const [path, ops] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(ops)) {
      const tag = op.tags?.[0] ?? "other";
      if (!byTag.has(tag)) byTag.set(tag, []);
      const perm = op["x-required-permission"] ? `\`${op["x-required-permission"]}\`` : op.security ? "signed in" : "none";
      byTag.get(tag).push(`| ${method.toUpperCase()} | \`${path}\` | ${perm} |`);
    }
  }
  const tags = [...byTag.keys()].sort();
  const count = [...byTag.values()].reduce((n, rows) => n + rows.length, 0);
  let body = `# API reference\n\n${count} operations in ${tags.length} groups, generated from \`docs/openapi.json\`, which \`scripts/generate_openapi.py\` derives from the server's own router. Paths, methods and required permissions are complete. **Request and response bodies are not described yet**; read the handler named in the OpenAPI file.\n\n`;
  body += "Regenerate the source with `python3 scripts/generate_openapi.py` from `medbrains/`; CI fails when it is stale (`--check`).\n\n";
  for (const tag of tags) {
    body += `## ${tag}\n\n| Method | Path | Permission |\n|---|---|---|\n${byTag.get(tag).sort().join("\n")}\n\n`;
  }
  page("api.md", "API reference", "Every MedBrains HTTP API operation with its method, path and required permission, generated from the server router's OpenAPI description.", body);
}

/** Variables named in .env.example, with the comment block above each. */
function envExample() {
  const vars = new Map();
  let comment = [];
  for (const line of readFileSync(join(ROOT, ".env.example"), "utf8").split("\n")) {
    const m = line.match(/^#?\s*([A-Z][A-Z0-9_]{2,})=(.*)$/);
    if (m) {
      vars.set(m[1], { example: m[2].trim(), note: comment.join(" ").trim() });
      comment = [];
    } else if (line.startsWith("#")) comment.push(line.replace(/^#\s?/, "").replace(/[─━═-]{3,}/g, "").trim());
    else comment = [];
  }
  return vars;
}

/** The env-var table: every variable the crates read or .env.example names. */
function envVars() {
  const reads = new Map();
  for (const file of rustFiles(join(ROOT, "crates"))) {
    const src = readFileSync(file, "utf8");
    for (const m of src.matchAll(READ)) {
      const crate = relative(join(ROOT, "crates"), file).split("/")[0];
      if (!reads.has(m[1])) reads.set(m[1], new Set());
      reads.get(m[1]).add(crate);
    }
  }
  const example = envExample();
  const names = [...new Set([...reads.keys(), ...example.keys()])].sort();
  const cell = (s) => s.replace(/\|/g, "\\|").replace(/[{}<>]/g, (c) => `&#${c.charCodeAt(0)};`);
  const rows = names.map((name) => {
    const ex = example.get(name);
    const value = SECRET.test(name) ? "**secret:** set in your secret store, never commit" : ex?.example ? `\`${cell(ex.example)}\`` : "";
    const where = reads.has(name) ? [...reads.get(name)].sort().map((c) => `\`${c}\``).join(", ") : "config file (`RawConfig`) or deploy kit";
    return `| \`${name}\` | ${value} | ${cell(ex?.note ?? "").slice(0, 240)} | ${where} |`;
  });
  let body = `# Environment variables\n\n${names.length} variables, generated from two sources: the variables the Rust crates read (\`env::var\` and the \`env_*\` helpers), and \`medbrains/.env.example\` with its comments. **Example** is the value \`.env.example\` uses for local development, not necessarily the compiled default; the server's own defaults are in \`crates/medbrains-server-core/src/config.rs\`. Settings layer as compiled defaults, then \`config.toml\`, then environment variables.\n\n`;
  body += "| Name | Example | What it does | Read by |\n|---|---|---|---|\n" + rows.join("\n") + "\n";
  page("env-vars.md", "Environment variables", "Every environment variable MedBrains reads, with its local example value, what it does and which crate reads it, generated from the code and .env.example.", body);
}

mkdirSync(OUT, { recursive: true });
apiReference();
envVars();
