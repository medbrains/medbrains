#!/usr/bin/env python3
"""Generate the web's registration catalogue and its fixtures, from the Rust.

    python3 scripts/generate_registration_catalogue.py           # write
    python3 scripts/generate_registration_catalogue.py --check    # fail if stale

The registration form — steps, fields, options and rules — is defined once, in
`crates/medbrains-clinical-core/src/registration/`. The server and both native
apps read it directly; the web reads this generated copy, and its TypeScript
port of the rules is held to the fixtures written here, case for case. A
hand-kept copy drifts; this one fails `--check` until regenerated.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCHEMAS = os.path.join(ROOT, "packages/schemas/src")
CATALOGUE_TS = os.path.join(SCHEMAS, "registration.generated.ts")
FIXTURES_JSON = os.path.join(SCHEMAS, "registration.fixtures.generated.json")

HEADER = """// GENERATED by scripts/generate_registration_catalogue.py from
// crates/medbrains-clinical-core/src/registration/. Do not edit by hand:
// change the Rust and regenerate (`make gen-registration`).

import type { RegistrationCatalogue } from "./registration-rules.js";

"""


def rust_json(which: str) -> str:
    env = dict(os.environ, CARGO_TARGET_DIR=os.environ.get("CARGO_TARGET_DIR", "/tmp/mb-target"))
    out = subprocess.run(
        ["cargo", "run", "-q", "-p", "medbrains-clinical-core", "--bin", "registration_catalogue", which],
        cwd=ROOT,
        env=env,
        check=True,
        capture_output=True,
        text=True,
    )
    return out.stdout


def biome_format(path: str, text: str) -> str:
    """The text as the repo's formatter writes it, so --check compares like with like."""
    out = subprocess.run(
        ["npx", "biome", "format", f"--stdin-file-path={os.path.relpath(path, ROOT)}"],
        cwd=ROOT,
        input=text,
        check=True,
        capture_output=True,
        text=True,
    )
    return out.stdout


def render() -> dict[str, str]:
    catalogue = json.loads(rust_json("catalogue"))
    fixtures = json.loads(rust_json("fixtures"))
    body = json.dumps(catalogue, indent=2, ensure_ascii=False)
    return {
        CATALOGUE_TS: biome_format(
            CATALOGUE_TS, f"{HEADER}export const registrationCatalogue: RegistrationCatalogue = {body};\n"
        ),
        FIXTURES_JSON: biome_format(FIXTURES_JSON, json.dumps(fixtures, indent=2, ensure_ascii=False) + "\n"),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    args = parser.parse_args()
    stale = []
    for path, text in render().items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if current == text:
            continue
        if args.check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print(f"wrote {os.path.relpath(path, ROOT)}")
    if stale:
        print("stale — run: python3 scripts/generate_registration_catalogue.py", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
