#!/usr/bin/env python3
"""Decision files are well formed, and their index is generated from them.

A decision is one small file in `medbrains/docs/decisions/`, so two pull requests that each
record one never touch the same lines (every PR used to append a row to `docs/DECISIONS.md`,
and every merge put the others into conflict). The file is named `YYYY-MM-DD-short-slug.md`:

    ---
    date: 2026-11-22
    title: One line saying what was decided
    status: decided            (or: proposed, or: reversal-of:<file or row>)
    area: ci                   (lowercase: ci, docs, pharmacy, billing, ...)
    ---

    ## What
    ## Why
    ## Rejected

  check_decisions.py                    # every file in the folder is valid
  check_decisions.py --base origin/X    # also warn if this branch added to DECISIONS.md
  check_decisions.py --index            # write decisions/README.md, newest first
  check_decisions.py --index --check    # fail if a README.md is there and out of date
  check_decisions.py --self-test
"""

from __future__ import annotations

import datetime
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDER = ROOT / "docs" / "decisions"
HISTORY = "medbrains/docs/DECISIONS.md"
NAME = re.compile(r"^(\d{4}-\d{2}-\d{2})-[a-z0-9]+(-[a-z0-9]+)*\.md$")
KEYS = ["date", "title", "status", "area"]
HEADINGS = ["## What", "## Why", "## Rejected"]
AREA = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def front_section(text: str) -> tuple[dict[str, str], list[str], str]:
    """The front section as a dict, its keys in file order, and the body after it."""
    lines = text.splitlines()
    if not lines or lines[0] != "---" or "---" not in lines[1:]:
        return {}, [], text
    end = lines.index("---", 1)
    pairs = [line.partition(":") for line in lines[1:end] if line.strip()]
    fields = {key.strip(): value.strip() for key, _, value in pairs}
    return fields, [key.strip() for key, _, _ in pairs], "\n".join(lines[end + 1 :])


def body_problems(body: str) -> list[str]:
    """The three headings must be there, in order, each with something under it."""
    found = [line for line in body.splitlines() if line.startswith("## ")]
    if found != HEADINGS:
        return [f"headings must be exactly {', '.join(HEADINGS)}, in that order"]
    sections = re.split(r"^## .*$", body, flags=re.MULTILINE)[1:]
    return [f"nothing under {h}" for h, s in zip(HEADINGS, sections) if not s.strip()]


def status_problem(status: str, names: set[str]) -> str | None:
    """`decided`, `proposed`, or `reversal-of:` naming a row or a file in the folder."""
    if status in ("decided", "proposed"):
        return None
    target = status.removeprefix("reversal-of:").strip()
    if not status.startswith("reversal-of:") or not target:
        return "status must be decided, proposed or reversal-of:<file or row>"
    if NAME.match(target) and target not in names:
        return f"status reverses {target}, which is not in the folder"
    return None


def problems(name: str, text: str, names: set[str]) -> list[str]:
    """Everything wrong with one decision file; empty when it is valid."""
    match = NAME.match(name)
    if not match:
        return ["name must be YYYY-MM-DD-short-slug.md (lowercase letters, digits, hyphens)"]
    fields, keys, body = front_section(text)
    if keys != KEYS:
        return [f"front section must be exactly {', '.join(KEYS)} between two --- lines"]
    out = []
    try:
        datetime.date.fromisoformat(match.group(1))
    except ValueError:
        out.append(f"{match.group(1)} is not a date")
    if fields["date"] != match.group(1):
        out.append("date must match the date in the file name")
    if not fields["title"]:
        out.append("title is empty")
    if not AREA.match(fields["area"]):
        out.append("area must be one lowercase word (hyphens allowed)")
    status = status_problem(fields["status"], names)
    return out + ([status] if status else []) + body_problems(body)


def decision_files(folder: Path = FOLDER) -> list[Path]:
    """Every file in the folder except the generated index, newest first."""
    if not folder.is_dir():
        return []
    return sorted((p for p in folder.iterdir() if p.name != "README.md"), reverse=True)


def index(files: list[Path]) -> str:
    """The generated README: one table row per decision, newest first."""
    rows = []
    for path in files:
        f, _, _ = front_section(path.read_text())
        title = f.get("title", "").replace("|", "\\|")
        rows.append(f"| {f.get('date')} | [{title}]({path.name}) | {f.get('status')} | {f.get('area')} |")
    head = (
        "# Decisions\n\n"
        "Generated by `medbrains/scripts/check_decisions.py --index`; do not edit or commit.\n"
        "Decisions before 2026-11-22 are in [`../DECISIONS.md`](../DECISIONS.md).\n\n"
        "| Date | Decision | Status | Area |\n|---|---|---|---|\n"
    )
    return head + "\n".join(rows) + "\n"


def check_folder() -> int:
    """Print every problem in the folder; 1 if there is one."""
    files = decision_files()
    names = {p.name for p in files}
    bad = 0
    for path in files:
        for problem in problems(path.name, path.read_text(), names):
            print(f"::error file=medbrains/docs/decisions/{path.name}::{problem}")
            bad = 1
    if not bad:
        print(f"check-decisions: OK ({len(files)} file(s))")
    return bad


def warn_if_history_grew(base: str) -> None:
    """Say so when this branch added a row to DECISIONS.md, which is closed to new rows."""
    diff = subprocess.run(
        ["git", "diff", "-U0", f"{base}...HEAD", "--", HISTORY],
        cwd=ROOT.parent, capture_output=True, text=True, check=False,
    ).stdout
    # ponytail: a warning while open pull requests still carry rows; make it an error after.
    if re.search(r"^\+\| *\d{4}-\d{2}-\d{2} *\|", diff, flags=re.MULTILINE):
        print(
            f"::warning file={HISTORY}::DECISIONS.md takes no new rows. Move yours to a file: "
            f"python3 medbrains/scripts/decision_row_to_file.py {base}"
        )


def self_test() -> int:
    """Known good and bad files against the rules, and the index order."""
    good = "---\ndate: 2026-11-22\ntitle: A: b\nstatus: decided\narea: ci\n---\n\n## What\na\n\n## Why\nb\n\n## Rejected\nc\n"
    name = "2026-11-22-one-file.md"
    assert problems(name, good, {name}) == []
    assert problems("2026-11-22_One.md", good, set())
    assert problems("2026-13-40-x.md", good.replace("11-22", "13-40"), set())
    assert problems("2026-11-21-x.md", good, set()) == ["date must match the date in the file name"]
    assert problems(name, good.replace("area: ci", "area: CI stuff"), set())
    assert problems(name, good.replace("title: A: b\n", ""), set())
    assert problems(name, good.replace("## Why\nb\n", "## Why\n"), set()) == ["nothing under ## Why"]
    assert problems(name, good.replace("## Rejected\nc\n", ""), set())
    assert problems(name, good.replace("decided", "done"), set())
    reversal = good.replace("decided", "reversal-of:2026-11-01-old.md")
    assert problems(name, reversal, set()) and not problems(name, reversal, {"2026-11-01-old.md"})
    assert not problems(name, good.replace("decided", "reversal-of:DECISIONS.md 2026-11-12 row"), set())
    assert front_section(good)[0]["title"] == "A: b"
    print("check-decisions self-test: OK")
    return 0


def main() -> int:
    """Dispatch the self-test, the index and the check."""
    args = sys.argv[1:]
    if args == ["--self-test"]:
        return self_test()
    if args and args[0] == "--index" and args[1:] in ([], ["--check"]):
        readme, text = FOLDER / "README.md", index(decision_files())
        if not args[1:]:
            readme.write_text(text)
            return 0
        stale = readme.exists() and readme.read_text() != text
        print("decisions/README.md is out of date" if stale else "decisions index: OK")
        return int(stale)
    if args and (len(args) != 2 or args[0] != "--base"):
        print(__doc__, file=sys.stderr)
        return 2
    if args:
        warn_if_history_grew(args[1])
    return check_folder()


if __name__ == "__main__":
    sys.exit(main())
