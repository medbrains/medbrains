#!/usr/bin/env python3
"""One manifest per brick: `bricks/<id>/brick.toml`, generated from what the code declares.

Each manifest carries the brick's id, name, description, the bricks it needs, its permission
groups, the routers its switch covers and their path prefixes, its background jobs, the tables
only its own crates write and its screens. Sources: `bricks.rs` (table and
jobs), the module seed and onboarding lists (descriptions), the router inventory, `access/screens.rs`, the
migrations and each crate's SQL. Nothing is invented: a field the code does not declare is empty.

`--check` fails when a manifest does not parse, the set of manifests differs from the bricks
the server knows, a `needs` names no brick, the needs form a cycle, a gated path prefix is
claimed by two bricks, or a checked-in manifest differs from what the code generates.

Tables are an inference, not a declaration: a table is a brick's when every crate that writes it
has routers switched by that brick and by no other. The server crate mounts every router and serves
many bricks, so it is never one brick's; what it writes is unowned. `--unowned` prints every
written table no brick owns, with the crates that write it. There is no `tests` field: a list of
test files went stale with every unrelated pull request that added one (test tagging is lane B3).

Run from `medbrains/`: python3 scripts/brick_manifests.py [--write | --check | --self-test | --unowned]
"""

import json
import re
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT.parent / "scripts"))
sys.path.insert(0, str(ROOT / "scripts"))
from brick_router_inventory import CALL, paths_of, rows  # noqa: E402
from check_bricks import SEED, read_bricks  # noqa: E402

OUT = ROOT / "bricks"
CRATES = ROOT / "crates"
BRICKS_RS = CRATES / "medbrains-core/src/bricks.rs"
SCREENS_RS = CRATES / "medbrains-core/src/access/screens.rs"
ONBOARDING = CRATES / "medbrains-onboarding/src/lib.rs"
MIGRATIONS = CRATES / "medbrains-db-migrations/src/migrations"
# Crates that write other bricks' tables to set a hospital up; they own none of them.
SETUP_CRATES = {"medbrains-seed", "medbrains-db-migrations", "medbrains-demo-seed"}
# The crate that mounts every router. Some of its own routers sit behind one brick's switch, but
# it also serves ABDM, audit, storage, the portal and more, so it is never a single brick's crate.
HOST_CRATE = "medbrains-server"
WRITE = re.compile(r"\b(?:INSERT INTO|UPDATE|DELETE FROM)\s+(?:public\.)?([a-z_0-9]+)")
HEADER = "# Generated by scripts/brick_manifests.py from the code. Do not edit by hand:\n# change the code it is read from, then run the script with --write.\n"


def names_and_descriptions() -> dict[str, tuple[str, str]]:
    """Brick id -> (name, description): names from `bricks.rs`, descriptions from the seed list
    and, for bricks a migration adds, from its `module_config` insert."""
    names = dict(re.findall(r'(?:brick\(|id: )"([a-z_]+)", (?:name: )?"([^"]+)"', BRICKS_RS.read_text()))
    described: dict[str, str] = {}
    for source in (SEED, ONBOARDING):
        for code, text in re.findall(r'\(\s*"([a-z_]+)",\s*"[^"]+",\s*"([^"]*)"', source.read_text()):
            described.setdefault(code, text)
    for sql in sorted(MIGRATIONS.glob("*.sql")):
        for code, text in re.findall(r"'([a-z_]+)',\s*'[^']+',\s*'([^']+)',\s*'[a-z_]+'::module_status", sql.read_text()):
            described.setdefault(code, text)
    return {ident: (name, described.get(ident, "")) for ident, name in names.items()}


def routers_by_brick() -> tuple[dict[str, list[dict]], dict[str, set[str]]]:
    """Brick id -> the routers its switch covers; and crate -> the bricks that gate its routers.
    The host crate is left out of the second map: it belongs to no brick."""
    routers: dict[str, list[dict]] = defaultdict(list)
    crates: dict[str, set[str]] = defaultdict(set)
    for row in (r for r in rows() if r["kind"] == "router"):
        for brick in [row["gate"]] if row["gate"] else sorted(row["checks"]):
            gate = "merge" if row["gate"] else "handlers"
            routers[brick].append({"router": row["router"], "crate": row["crate"], "gate": gate})
            if row["crate"] != HOST_CRATE:
                crates[row["crate"]].add(brick)
    return routers, crates


def claimed_prefixes(routers: dict[str, list[dict]]) -> dict[str, list[str]]:
    """Brick id -> the path prefixes of its merge-gated routers, cut one segment deeper where
    two bricks would otherwise share one (`/api/nurse` is IPD's and Nursing's)."""
    paths = {b: [p for r in rs if r["gate"] == "merge" for c in CALL.findall(r["router"]) for p in paths_of(c)] for b, rs in routers.items()}
    cut = lambda path, depth: "/".join(path.split("/")[:depth])  # noqa: E731
    owners: dict[str, set[str]] = defaultdict(set)
    for brick, found in paths.items():
        for path in found:
            owners[cut(path, 3)].add(brick)
    return {b: sorted({cut(p, 3 if len(owners[cut(p, 3)]) == 1 else 4) for p in found}) for b, found in paths.items()}


def table_writers() -> dict[str, set[str]]:
    """Table -> the crates whose code writes it (setup crates aside), for tables a migration creates."""
    known: set[str] = set()
    for sql in MIGRATIONS.glob("*.sql"):
        known |= set(re.findall(r"CREATE TABLE (?:IF NOT EXISTS )?(?:public\.)?([a-z_0-9]+)", sql.read_text()))
    writers: dict[str, set[str]] = defaultdict(set)
    for path in CRATES.glob("*/src/**/*.rs"):
        crate = path.relative_to(CRATES).parts[0]
        if crate not in SETUP_CRATES:
            for table in WRITE.findall(path.read_text(errors="ignore")):
                if table in known:
                    writers[table].add(crate)
    return writers


def split_tables(writers: dict[str, set[str]], crates: dict[str, set[str]]) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """(brick id -> the tables only that brick's crates write, table -> writers for the rest).
    A table is a brick's only when every writer is a crate of that one brick; a writer that
    serves several bricks, or none (the host crate included), leaves the table unowned."""
    owned: dict[str, list[str]] = defaultdict(list)
    unowned: dict[str, list[str]] = {}
    for table in sorted(writers):
        bricks = [crates.get(crate, set()) for crate in writers[table]]
        if all(len(b) == 1 for b in bricks) and len(set.union(*bricks)) == 1:
            owned[next(iter(bricks[0]))].append(table)
        else:
            unowned[table] = sorted(writers[table])
    return owned, unowned


def manifests() -> dict[str, str]:
    """Brick id -> the text of its `brick.toml`."""
    table, _ = read_bricks()
    described = names_and_descriptions()
    routers, crates = routers_by_brick()
    prefixes, (tables, _) = claimed_prefixes(routers), split_tables(table_writers(), crates)
    text = BRICKS_RS.read_text()
    jobs = re.findall(r'BrickJob \{ id: "([a-z_]+)".*?bricks: &\[([^\]]*)\]', text)
    add_ons = set(re.findall(r'id: "([a-z_]+)"[^}]*add_on: true', text))
    screens = re.findall(r'route: "([^"]+)".*?brick: Some\("([a-z_]+)"\)', SCREENS_RS.read_text())
    out = {}
    for ident, brick in table.items():
        fields = {
            "manifest_version": 1, "id": ident, "name": described[ident][0], "description": described[ident][1],
            "add_on": ident in add_ons, "needs": brick["deps"], "permissions": brick["groups"],
            "prefixes": prefixes.get(ident, []),
            "jobs": [job for job, served in jobs if f'"{ident}"' in served],
            "tables": tables.get(ident, []),
            "screens": [route for route, owner in screens if owner == ident],
        }
        body = "".join(f"{key} = {toml_value(value)}\n" for key, value in fields.items())
        for router in routers.get(ident, []):
            body += "\n[[routers]]\n" + "".join(f"{key} = {toml_value(value)}\n" for key, value in router.items())
        out[ident] = HEADER + body
    return out


def toml_value(value: object) -> str:
    """A TOML scalar, or a list with one item per line once it has more than three."""
    if isinstance(value, list):
        items = [json.dumps(item, ensure_ascii=False) for item in value]
        return "[" + ", ".join(items) + "]" if len(items) <= 3 else "[\n" + "".join(f"    {i},\n" for i in items) + "]"
    return json.dumps(value, ensure_ascii=False)


def cycle_in(needs: dict[str, list[str]]) -> list[str]:
    """A chain of bricks that needs itself, or nothing. Each brick is finished once."""
    done: set[str] = set()

    def walk(ident: str, trail: list[str]) -> list[str]:
        """The cycle reached from `ident`, given the bricks already on the way to it."""
        if ident in trail:
            return trail[trail.index(ident) :] + [ident]
        if ident in done:
            return []
        found = next((c for dep in needs.get(ident, []) if (c := walk(dep, trail + [ident]))), [])
        done.add(ident)
        return found

    return next((c for ident in needs if (c := walk(ident, []))), [])


def prefix_clashes(prefixes: dict[str, list[str]]) -> list[str]:
    """Path prefixes two bricks both claim, the same one or one inside the other."""
    claims = sorted((prefix, brick) for brick, found in prefixes.items() for prefix in found)
    return [
        f"{a} ({ba}) and {b} ({bb})"
        for at, (a, ba) in enumerate(claims)
        for b, bb in claims[at + 1 :]
        if ba != bb and (a == b or b.startswith(a + "/"))
    ]


def problems(expected: dict[str, str]) -> list[str]:
    """Everything wrong with the checked-in manifests."""
    found, parsed = [], {}
    for path in sorted(OUT.glob("*/brick.toml")):
        try:
            parsed[path.parent.name] = tomllib.loads(path.read_text())
        except tomllib.TOMLDecodeError as error:
            found.append(f"{path.relative_to(ROOT)} does not parse: {error}")
            continue
        if parsed[path.parent.name].get("id") != path.parent.name:
            found.append(f"{path.relative_to(ROOT)} has id {parsed[path.parent.name].get('id')!r}")
        if path.read_text() != expected.get(path.parent.name):
            found.append(f"{path.relative_to(ROOT)} differs from the code: run scripts/brick_manifests.py --write")
    for ident in sorted(set(expected) ^ set(parsed)):
        found.append(f"brick {ident} is in {'the server' if ident in expected else 'bricks/'} only")
    needs = {ident: manifest.get("needs", []) for ident, manifest in parsed.items()}
    found += [f"{ident} needs {dep}, which is no brick" for ident, deps in needs.items() for dep in deps if dep not in parsed]
    if cycle := cycle_in(needs):
        found.append("needs form a cycle: " + " -> ".join(cycle))
    clashes = prefix_clashes({ident: manifest.get("prefixes", []) for ident, manifest in parsed.items()})
    return found + [f"gated prefix claimed by two bricks: {clash}" for clash in clashes]


def self_test() -> int:
    """The cycle and clash checks, on fixed input."""
    assert cycle_in({"a": ["b"], "b": ["c"], "c": ["a"]}) == ["a", "b", "c", "a"]
    assert cycle_in({"a": ["b"], "b": [], "c": ["a", "b"]}) == []
    assert prefix_clashes({"x": ["/api/a"], "y": ["/api/a/b"]}) == ["/api/a (x) and /api/a/b (y)"]
    assert prefix_clashes({"x": ["/api/a", "/api/ab"], "y": ["/api/abc"]}) == []
    owned, unowned = split_tables(
        {"t_own": {"c-a"}, "t_host": {"c-a", HOST_CRATE}, "t_two": {"c-two"}, "t_none": {"c-x"}},
        {"c-a": {"a"}, "c-two": {"a", "b"}},
    )
    assert owned == {"a": ["t_own"]} and sorted(unowned) == ["t_host", "t_none", "t_two"]
    assert HOST_CRATE not in routers_by_brick()[1]
    assert tomllib.loads("v = " + toml_value(["a", "b", "c", "d"])) == {"v": ["a", "b", "c", "d"]}
    print("brick_manifests self-test: ok")
    return 0


def main() -> int:
    """Write the manifests, or check them; 1 on any failure."""
    if "--self-test" in sys.argv:
        return self_test()
    if "--unowned" in sys.argv:
        _, unowned = split_tables(table_writers(), routers_by_brick()[1])
        print("\n".join(f"{table}: {', '.join(crates)}" for table, crates in unowned.items()))
        print(f"written tables no brick owns: {len(unowned)}")
        return 0
    expected = manifests()
    if "--write" in sys.argv:
        for ident, text in expected.items():
            (OUT / ident).mkdir(parents=True, exist_ok=True)
            (OUT / ident / "brick.toml").write_text(text)
    found = problems(expected)
    print(f"brick manifests: {len(expected)}")
    for problem in found:
        print(f"FAIL {problem}")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
