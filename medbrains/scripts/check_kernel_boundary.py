#!/usr/bin/env python3
"""Apps reach the trusted core through the kernel, and that only gets better.

    python3 scripts/check_kernel_boundary.py            # check (CI)
    python3 scripts/check_kernel_boundary.py --update   # record an improvement

RFC-HOSPITAL-OS §3 / §6 phase K2. The kernel (`crates/medbrains-kernel`) owns
tenancy (the RLS transaction), authorisation, audit, sequences, the object
store and config. An app crate that does any of those itself — opens a tenant
transaction, asks the authz engine, writes the audit chain — has a second path
past the core that the core cannot police.

For every app crate this counts:

- runtime dependencies on the kernel's internals (`medbrains-db`,
  `medbrains-authz`, `medbrains-authz-gate`); dev-dependencies don't count;
- source sites that do a kernel-owned job directly (PATTERNS below), outside
  comments and inline `#[cfg(test)] mod … { }` blocks.

The result is compared with `crates/medbrains-kernel/boundary.txt`:

- a crate that got worse, or a new crate with any direct access, FAILS;
- a crate that got better, or a new clean crate, fails until `--update`
  records it — so the file always matches the code;
- `--update` refuses to record a regression.

The same file is the single source for Admin → Kernel: the kernel's build.rs
reads it, so the page shows exactly what CI enforces.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRATES = ROOT / "crates"
KERNEL = CRATES / "medbrains-kernel"
BASELINE = KERNEL / "boundary.txt"

INTERNALS = ("medbrains-db", "medbrains-authz", "medbrains-authz-gate")

PATTERNS = {
    "tenancy": r"\bset_\w*context\(|tenant_conn\(|\b(db|pool)\.begin\(\)"
    r"|'app\.tenant_id'|\(\s*&state\.db\s*\)",
    "authz": r"medbrains_authz(_gate)?::|\.authz\s*\.\s*(check|bulk_check|list_accessible|expand"
    r"|write_tuple|grant_raw|revoke_tuple)\(|\bauthorization::\w",
    "audit": r"\bAuditLogger\b",
    "sequences": r"next_sequence\(",
    "store": r"\bdocuments_store\b|\bobject_store::|\bstate\.s3\b",
    "config": r"\btenant_config::",
}
SITE = re.compile("|".join(f"(?:{p})" for p in PATTERNS.values()))

HEADER = """\
# Kernel boundary baseline — generated by scripts/check_kernel_boundary.py --update.
# crate  status  direct-sites  internal-deps
# status: on_facade (kernel only) · partial (kernel + direct access) · not_yet (no kernel)
# Read by medbrains-kernel/build.rs for Admin → Kernel. Do not hand-edit.
"""


def runtime_deps(manifest: str) -> set[str]:
    """Names under `[dependencies]` only."""
    deps, runtime = set(), False
    for line in manifest.splitlines():
        line = line.strip()
        if line.startswith("["):
            runtime = line == "[dependencies]"
        elif runtime and "=" in line and not line.startswith("#"):
            deps.add(line.split("=", 1)[0].strip())
    return deps


def count_sites(src: Path) -> int:
    total = 0
    for path in sorted(src.rglob("*.rs")):
        lines = iter(path.read_text(encoding="utf-8").splitlines())
        for line in lines:
            if line.startswith("#[cfg(test)]"):
                head = next(lines, "")
                if re.match(r"mod \w+ \{", head):
                    depth = head.count("{") - head.count("}")
                    while depth > 0:  # skip the inline test module
                        body = next(lines, None)
                        if body is None:
                            break
                        depth += body.count("{") - body.count("}")
                    continue
                line = head
            code = line.split("//", 1)[0]
            total += len(SITE.findall(code))
    return total


def scan() -> dict[str, tuple[str, int, tuple[str, ...]]]:
    blocks = runtime_deps((KERNEL / "Cargo.toml").read_text(encoding="utf-8"))
    rows = {}
    for manifest in sorted(CRATES.glob("medbrains-*/Cargo.toml")):
        name = manifest.parent.name
        if name == "medbrains-kernel" or name in blocks:
            continue  # the kernel and its building blocks are the core, not apps
        deps = runtime_deps(manifest.read_text(encoding="utf-8"))
        internal = tuple(d for d in INTERNALS if d in deps)
        sites = count_sites(manifest.parent / "src") if (manifest.parent / "src").exists() else 0
        on_kernel = "medbrains-kernel" in deps
        if not on_kernel:
            status = "not_yet"
        elif internal or sites:
            status = "partial"
        else:
            status = "on_facade"
        rows[name] = (status, sites, internal)
    return rows


def read_baseline() -> dict[str, tuple[str, int, tuple[str, ...]]]:
    rows = {}
    for line in BASELINE.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        name, status, sites, deps = line.split()
        rows[name] = (status, int(sites), () if deps == "-" else tuple(deps.split(",")))
    return rows


def write_baseline(rows: dict[str, tuple[str, int, tuple[str, ...]]]) -> None:
    body = "".join(
        f"{name} {status} {sites} {','.join(deps) or '-'}\n"
        for name, (status, sites, deps) in sorted(rows.items())
    )
    BASELINE.write_text(HEADER + body, encoding="utf-8")


RANK = {"on_facade": 0, "partial": 1, "not_yet": 2}


def compare(live, base) -> tuple[list[str], list[str]]:
    worse, better = [], []
    for name, (status, sites, deps) in live.items():
        if name not in base:
            (worse if sites or deps else better).append(
                f"{name}: new crate ({status}, {sites} direct sites, deps {list(deps)})"
            )
            continue
        b_status, b_sites, b_deps = base[name]
        added = set(deps) - set(b_deps)
        if sites > b_sites or added:
            worse.append(f"{name}: direct sites {b_sites} -> {sites}, new internal deps {sorted(added)}")
        elif (status, sites, deps) != (b_status, b_sites, b_deps):
            better.append(f"{name}: {b_status}/{b_sites} -> {status}/{sites}")
    better += [f"{name}: crate removed" for name in base.keys() - live.keys()]
    return worse, better


def main() -> int:
    live = scan()
    base = read_baseline() if BASELINE.exists() else {}
    worse, better = compare(live, base)
    on = sum(1 for s, _, _ in live.values() if s == "on_facade")
    summary = f"{on} of {len(live)} modules on the kernel"
    if worse and base:
        print("✗ kernel boundary got worse — use medbrains_kernel instead:")
        for w in worse:
            print(f"  {w}")
        return 1
    if "--update" in sys.argv:  # a missing baseline is seeded from the code as it stands
        write_baseline(live)
        print(f"✓ baseline updated ({summary})")
        return 0
    if better:
        print("✗ kernel boundary improved but the baseline still holds the old numbers:")
        for b in better:
            print(f"  {b}")
        print("  run: python3 scripts/check_kernel_boundary.py --update")
        return 1
    print(f"✓ kernel boundary holds ({summary})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
