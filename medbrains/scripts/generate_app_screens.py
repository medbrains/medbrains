#!/usr/bin/env python3
"""Write the web copy of the screen registry and the brick manifests: every menu screen, the app it
belongs to, and one manifest per app brick.

    python3 scripts/generate_app_screens.py           # rewrite packages/types/src/app-screens.generated.ts
    python3 scripts/generate_app_screens.py --check   # CI: fail when the committed copy differs
    python3 scripts/generate_app_screens.py --self-test

The source is the one screen registry, `crates/medbrains-core/src/access/screens.rs`, plus every
brick's name from `crates/medbrains-core/src/bricks.rs`. It reads those files the way
`generate_permissions_ts.py` reads `permissions.rs`, so CI can check the copy without a Rust
toolchain. The Rust tests in `screens.rs` check that every permission named is real and that every
app row names a known brick. A row with no brick is a core screen and is written `brick: null`.

Each brick's manifest joins its `bricks.rs` row (name, dependencies, permission groups, Settings
sections, background jobs), its screens from the registry, and its typed actions (with their data
classes) from `crates/medbrains-health-services/src/actions.rs`. Generating fails when a screen or
action names no brick, or a Settings section is unknown to `apps/web/src/config/settings-tabs.ts`
or claimed twice, so the tables cannot drift apart.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCREENS_RS = ROOT / "crates/medbrains-core/src/access/screens.rs"
BRICKS_RS = ROOT / "crates/medbrains-core/src/bricks.rs"
ACTIONS_RS = ROOT / "crates/medbrains-health-services/src/actions.rs"
SETTINGS_TS = ROOT / "apps/web/src/config/settings-tabs.ts"
OUT = ROOT / "packages/types/src/app-screens.generated.ts"

ROW = re.compile(r"^\s*ScreenDef \{ (.*) \},\s*$")
FIELD = re.compile(r'(\w+): (Some\("[^"]*"\)|"[^"]*"|None|&\[\]|ScreenGroup::\w+|[A-Z_]+)')
GROUPS = {"Essential": "essential", "Advanced": "advanced", "DevOnly": "dev_only"}
CONST_LIST = re.compile(r"const ([A-Z_]+): &\[&str\] = &\[(.*?)\];", re.DOTALL)
BRICK = re.compile(r'brick\("([a-z_]+)", "([^"]+)"|Brick \{ id: "([a-z_]+)", name: "([^"]+)"')
QUOTED = re.compile(r'"([^"]+)"')
ACTION = re.compile(r"ActionDef \{(.*?)\n    \},", re.DOTALL)
SETTINGS_TAB = re.compile(r'^\s+value: "([a-z0-9-]+)",$', re.M)
MANIFEST_VERSION = re.compile(r"pub const MANIFEST_VERSION: u32 = (\d+);")
# Screens that hold only the signed-in person's own items, so no permission fits (the approvals
# inbox: there is no permission for having decisions waiting). Every other screen must name one.
PERSONAL_SCREENS = {"/approvals"}

HEADER = """// Generated by scripts/generate_app_screens.py from crates/medbrains-core/src/access/screens.rs; do not edit.
// Regenerate: python3 scripts/generate_app_screens.py

/** One menu screen. `brick` is the app whose side panel lists it; `null` is a core screen. */
export interface AppScreen {
  brick: string | null;
  path: string;
  labelKey: string;
  icon: string;
  /** Held as well as one of `anyOf` (when it has any); `null` with no `anyOf` is ungated. */
  permission: string | null;
  anyOf: readonly string[];
  /** Where the menu lists it: as usual, under Administration's "Advanced", or only in a dev build. */
  group: "essential" | "advanced" | "dev_only";
}

/** Every menu screen: each app's in panel order, apps in brick order, then the core screens. */
export const APP_SCREENS: readonly AppScreen[] = [
"""


def value(raw: str, lists: dict[str, list[str]]) -> str | list[str] | None:
    """One Rust field value as Python: a string, a list of strings, or None."""
    if raw == "None":
        return None
    if raw == "&[]":
        return []
    if raw in lists:
        return lists[raw]
    if raw.startswith("ScreenGroup::"):
        return GROUPS[raw.removeprefix("ScreenGroup::")]
    return raw.removeprefix("Some(").removesuffix(")").strip('"')


def panel_rows(text: str) -> list[dict]:
    """Every registry row, in table order."""
    lists = {name: re.findall(r'"([^"]+)"', body) for name, body in CONST_LIST.findall(text)}
    rows = []
    for line in text.splitlines():
        m = ROW.match(line)
        if not m:
            continue
        rows.append({k: value(v, lists) for k, v in FIELD.findall(m.group(1))})
    return rows


def brick_names(text: str) -> list[tuple[str, str]]:
    """Every brick's id and display name, in table order."""
    return [(a or c, b or d) for a, b, c, d in BRICK.findall(text)]


def brick_rows(text: str) -> list[dict]:
    """Every brick's declared manifest fields, in table order."""
    table = text[text.index("pub const BRICKS") : text.index("\n];\n", text.index("pub const BRICKS"))]
    rows = []
    for line in table.splitlines():
        line = line.strip()
        if line.startswith("brick("):
            lists = re.findall(r"&\[([^\]]*)\]", line)
            settings = re.search(r"with_settings\(&\[([^\]]*)\]", line)
            deps, groups, jobs = lists[0], lists[1], ""
        elif line.startswith("Brick {"):
            field = lambda name: re.search(name + r": &\[([^\]]*)\]", line).group(1)  # noqa: E731
            deps, groups, jobs = field("depends_on"), field("permission_groups"), field("background_jobs")
            settings = re.search(r"settings: &\[([^\]]*)\]", line)
        else:
            continue
        ident, name = QUOTED.findall(line)[:2]
        rows.append({
            "id": ident, "name": name, "dependsOn": QUOTED.findall(deps),
            "permissionGroups": QUOTED.findall(groups),
            "settings": QUOTED.findall(settings.group(1)) if settings else [],
            "backgroundJobs": QUOTED.findall(jobs),
        })
    return rows


def action_rows(text: str) -> list[dict]:
    """Every typed action's id, brick and data classes (`DataClass::RoutineX` -> `routine_x`)."""
    rows = []
    for body in ACTION.findall(text):
        classes = re.search(r"data_classes: &\[([^\]]*)\]", body).group(1)
        rows.append({
            "id": re.search(r'id: "([^"]+)"', body).group(1),
            "brick": re.search(r'module: "([^"]+)"', body).group(1),
            "permission": re.search(r"permission: permissions::([\w:]+)", body).group(1),
            "dataClasses": [re.sub(r"(?<!^)([A-Z])", r"_\1", c).lower()
                            for c in re.findall(r"DataClass::(\w+)", classes)],
        })
    return rows


def permission_codes() -> dict[str, str]:
    """`opd::queue::LIST` -> `opd.queue.list`, from permissions.rs (the permissions generator's parser)."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from generate_permissions_ts import rust_permissions

    return {f"{module}::{name}": code for module, name, code, _ in rust_permissions()}


def manifests(screens: list[dict], bricks: list[dict], actions: list[dict], tabs: set[str],
              codes: dict[str, str]) -> list[dict]:
    """One manifest per brick; raises ValueError naming every disagreement between the tables."""
    ids = {b["id"] for b in bricks}
    problems = [f"screen {r['route']} names unknown brick {r['brick']}" for r in screens
                if r["brick"] and r["brick"] not in ids]
    problems += [f"screen {r['route']} needs no permission" for r in screens
                 if not r["required_permission"] and not r["any_of"] and r["route"] not in PERSONAL_SCREENS]
    problems += [f"action {a['id']} names unknown brick {a['brick']}" for a in actions if a["brick"] not in ids]
    problems += [f"action {a['id']} names unknown permission {a['permission']}" for a in actions
                 if a["permission"] not in codes]
    claimed: dict[str, str] = {}
    for b in bricks:
        for key in b["settings"]:
            if key not in tabs:
                problems.append(f"{b['id']} plugs in Settings section {key}, which settings-tabs.ts lacks")
            if key in claimed:
                problems.append(f"Settings section {key} is claimed by {claimed[key]} and {b['id']}")
            claimed[key] = b["id"]
    if problems:
        raise ValueError("\n".join(problems))
    out = []
    for b in bricks:
        own = [r for r in screens if r["brick"] == b["id"]]
        acts = [a for a in actions if a["brick"] == b["id"]]
        classes = sorted({c for a in acts for c in a["dataClasses"]})
        out.append({**b, "icon": own[0]["icon"] if own else None,
                    "screens": [{"path": r["route"], "permission": r["required_permission"],
                                 "anyOf": r["any_of"]} for r in own],
                    "actions": [{"id": a["id"], "permission": codes[a["permission"]],
                                 "dataClasses": a["dataClasses"]} for a in acts],
                    "dataClasses": classes})
    return out


MANIFEST_DOC = """
/** One app brick's manifest: what it is, what it shows, what it runs. Generated from Rust. */
export interface BrickManifest {
  id: string;
  name: string;
  /** Tabler icon name: the brick's first screen's. `null` for a brick with no screen. */
  icon: string | null;
  dependsOn: readonly string[];
  permissionGroups: readonly string[];
  /**
   * Its menu screens: the route (every route under it belongs to the brick too) and the
   * permission it needs, as in `AppScreen`. Shown only while the brick is on AND it is held.
   */
  screens: readonly { path: string; permission: string | null; anyOf: readonly string[] }[];
  /** Its typed actions (`docs/architecture/ACTIONS.md`): the permission each runs under and the
   * data classes it returns. The server decides each call; this is for display only. */
  actions: readonly { id: string; permission: string; dataClasses: readonly string[] }[];
  /** The Settings sections (tab values) it plugs in; hidden while the brick is off. */
  settings: readonly string[];
  /** Background jobs it runs. Reserved for brick-aware startup; empty today. */
  backgroundJobs: readonly string[];
  /** The data classes its actions return. */
  dataClasses: readonly string[];
}
"""


def render(screens_rs: str, bricks_rs: str, actions_rs: str = "", settings_ts: str = "",
           codes: dict[str, str] | None = None) -> str:
    """The whole generated TypeScript module: the screen rows, then one manifest per brick."""
    q = json.dumps  # None -> null
    screens = panel_rows(screens_rs)
    lines = [
        f"  {{ brick: {q(r['brick'])}, path: {q(r['route'])}, labelKey: {q(r['nav_key'])}, "
        f"icon: {q(r['icon'])}, permission: {q(r['required_permission'])}, "
        f"anyOf: [{', '.join(q(c) for c in r['any_of'])}], group: {q(r['group'])} }},\n"
        for r in screens
    ]
    built = manifests(screens, brick_rows(bricks_rs), action_rows(actions_rs),
                      set(SETTINGS_TAB.findall(settings_ts)), codes if codes is not None else permission_codes())
    version = MANIFEST_VERSION.search(bricks_rs)
    keys = ("id", "name", "icon", "dependsOn", "permissionGroups", "screens", "actions",
            "settings", "backgroundJobs", "dataClasses")
    def ts(value: object) -> str:
        """A JSON value as a TS literal with bare object keys, the generated file's style."""
        return re.sub(r'"(\w+)":', r"\1:", json.dumps(value, separators=(", ", ": ")))

    rows = [f"  {q(m['id'])}: {{ " + ", ".join(f"{k}: {ts(m[k])}" for k in keys) + " },\n" for m in built]
    return (
        HEADER
        + "".join(lines)
        + "];\n"
        + MANIFEST_DOC
        + "\n/** The manifest schema version (`bricks::MANIFEST_VERSION`). */\n"
        + f"export const BRICK_MANIFEST_VERSION = {version.group(1) if version else 0};\n"
        + "\n/** Every app brick's manifest, by `module_config.code`, in table order. */\n"
        + "export const BRICK_MANIFESTS: Readonly<Record<string, BrickManifest>> = {\n"
        + "".join(rows)
        + "};\n"
    )


def self_test() -> None:
    """The parsing rules, on a small sample."""
    rs = (
        'const ANY: &[&str] = &[\n    "a.b",\n    "c.d",\n];\n'
        '    ScreenDef { code: "x", label: "X", route: "/x", module: "m", required_permission: Some("a.b"), '
        'icon: "IconX", nav_key: "xKey", brick: Some("opd"), any_of: ANY, group: ScreenGroup::Essential },\n'
        '    ScreenDef { code: "y", label: "Y", route: "/approvals", module: "m", required_permission: None, '
        'icon: "IconY", nav_key: "yKey", brick: None, any_of: &[], group: ScreenGroup::DevOnly },\n'
    )
    rows = panel_rows(rs)
    assert [r["route"] for r in rows] == ["/x", "/approvals"], "every row"
    assert rows[1]["brick"] is None and rows[1]["required_permission"] is None, "a core row"
    assert rows[0]["any_of"] == ["a.b", "c.d"], "a named list resolves"
    assert [r["group"] for r in rows] == ["essential", "dev_only"], "a group reads as its web name"
    names = brick_names('brick("opd", "OPD / Outpatient", &[]\n    Brick { id: "companion", name: "Patient Companion",')
    assert names == [("opd", "OPD / Outpatient"), ("companion", "Patient Companion")]
    bricks = (
        "pub const MANIFEST_VERSION: u32 = 1;\npub const BRICKS: &[Brick] = &[\n"
        '    brick("opd", "OPD / Outpatient", &["registration"], &["opd"], None).with_settings(&["tpl"]),\n'
        '    brick("registration", "Patient Registration", &[], &["patients"], None),\n];\n'
    )
    actions = (
        '    ActionDef {\n        id: "opd.queue.today",\n        module: "opd",\n'
        "        permission: permissions::opd::queue::LIST,\n"
        "        data_classes: &[DataClass::Identifying, DataClass::Routine],\n    },\n"
    )
    tabs = '    value: "tpl",\n'
    codes = {"opd::queue::LIST": "opd.queue.list"}
    out = render(rs, bricks, actions, tabs, codes)
    assert 'permission: "a.b", anyOf: ["a.b", "c.d"], group: "essential" },' in out, "the row layout"
    assert '{ brick: null, path: "/approvals", labelKey: "yKey", icon: "IconY", permission: null, anyOf: [], group: "dev_only" },' in out
    assert "export const BRICK_MANIFEST_VERSION = 1;" in out, "the schema version"
    assert (
        '  "opd": { id: "opd", name: "OPD / Outpatient", icon: "IconX", dependsOn: ["registration"], '
        'permissionGroups: ["opd"], screens: [{path: "/x", permission: "a.b", anyOf: ["a.b", "c.d"]}], '
        'actions: [{id: "opd.queue.today", permission: "opd.queue.list", dataClasses: ["identifying", "routine"]}], '
        'settings: ["tpl"], backgroundJobs: [], dataClasses: ["identifying", "routine"] },\n'
    ) in out, "a manifest joins its row, screens and actions"
    for broken, why in (
        ((rs, bricks, actions, ""), "an unknown Settings section"),
        ((rs.replace('Some("a.b"), icon: "IconX"', 'None, icon: "IconX"').replace("any_of: ANY", "any_of: &[]"),
          bricks, actions, tabs), "a screen with no permission"),
        ((rs, bricks, actions.replace("queue::LIST", "queue::NOPE"), tabs), "an action with no permission"),
        ((rs.replace('Some("opd")', 'Some("lab")'), bricks, actions, tabs), "a screen of no brick"),
        ((rs, bricks, actions.replace('"opd",', '"lab",'), tabs), "an action of no brick"),
        ((rs, bricks.replace("None),\n];", 'None).with_settings(&["tpl"]),\n];'), actions, tabs), "a twice-claimed section"),
    ):
        try:
            render(*broken, codes)
        except ValueError:
            continue
        raise AssertionError(f"{why} must fail")
    print("app-screens self-test: ok")


def main(argv: list[str]) -> int:
    """Rewrite or check the generated copy."""
    if "--self-test" in argv:
        self_test()
        return 0
    try:
        expected = render(SCREENS_RS.read_text(), BRICKS_RS.read_text(), ACTIONS_RS.read_text(),
                          SETTINGS_TS.read_text())
    except ValueError as disagreement:
        print(f"brick manifests disagree with their tables:\n{disagreement}")
        return 1
    if "--check" in argv:
        if OUT.read_text() != expected:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 scripts/generate_app_screens.py")
            return 1
        print("app-screens: generated copy is current")
        return 0
    OUT.write_text(expected)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
