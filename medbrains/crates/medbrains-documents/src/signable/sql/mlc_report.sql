-- Signable payload: mlc_report. Binds $1 tenant, $2 record; authorship is checked apart (signable.rs).
SELECT jsonb_build_object('schema',
    'medbrains.signable.mlc_report.v2',
    'record_type',
    'mlc_report',
    'record_id', m.id,
    'tenant_id', m.tenant_id,
    'er_visit_id', m.er_visit_id,
    'admission_id', m.admission_id,
    'patient_id', m.patient_id,
    'patient', jsonb_build_object('id', pat.id,
    'uhid', pat.uhid,
    'name', CONCAT_WS(' ', NULLIF(pat.prefix,
    ''), pat.first_name, NULLIF(pat.middle_name,
    ''), pat.last_name),
    'gender', pat.gender,
    'date_of_birth', pat.date_of_birth),
    'mlc_number', m.mlc_number,
    'case_type', m.case_type,
    'nature_of_case', m.nature_of_case,
    'police', jsonb_build_object('fir_number', m.fir_number,
    'station', m.police_station,
    'officer_name', m.police_officer_name,
    'officer_rank', m.police_officer_rank,
    'dd_number', m.police_dd_number),
    'informant', jsonb_build_object('brought_by', m.brought_by,
    'name', m.informant_name,
    'relation', m.informant_relation,
    'contact', m.informant_contact),
    'incident', jsonb_build_object('history', m.history_of_incident,
    'alleged_history', m.alleged_history,
    'at', m.date_time_of_incident,
    'place', m.place_of_incident,
    'weapon', m.weapon_used),
    'condition_on_arrival', m.condition_on_arrival,
    'examination_findings', m.examination_findings,
    'examined_at', m.examined_at,
    'treatment_given', m.treatment_given,
    'samples_handed_to', m.samples_handed_to,
    'medical_opinion', m.medical_opinion,
    'opinion', m.opinion,
    'is_pocso', m.is_pocso,
    'is_death_case', m.is_death_case,
    'cause_of_death', m.cause_of_death,
    'patient_condition_at_discharge', m.patient_condition_at_discharge,
    'examining_doctor_id', m.examining_doctor_id,
    'registration_date', m.registration_date,
    'registration_time', m.registration_time,
    'injuries', COALESCE((SELECT jsonb_agg(jsonb_build_object(
    'id', i.id,
    'injury_number', i.injury_number,
    'injury_type', i.injury_type,
    'nature', i.nature,
    'location', i.location,
    'body_site_code', i.body_site_code,
    'body_site_laterality', i.body_site_laterality,
    'size_cm', i.size_cm,
    'description', i.description,
    'probable_age', i.probable_age,
    'probable_weapon', i.probable_weapon) ORDER BY i.injury_number, i.id)
FROM mlc_injuries i
WHERE i.tenant_id = m.tenant_id AND i.mlc_case_id = m.id AND i.deleted_at IS NULL),
    '[]'::jsonb))
FROM mlc_cases m
JOIN patients pat ON pat.tenant_id = m.tenant_id AND pat.id = m.patient_id
WHERE m.tenant_id = $1 AND m.id = $2 AND m.deleted_at IS NULL
