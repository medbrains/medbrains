-- Signable payload: vitals. Binds $1 tenant, $2 record; authorship is checked apart (signable.rs).
SELECT jsonb_build_object('schema',
    'medbrains.signable.vitals.v2',
    'record_type',
    'vitals',
    'record_id', vt.id,
    'tenant_id', vt.tenant_id,
    'encounter_id', vt.encounter_id,
    'patient_id', pat.id,
    'patient', jsonb_build_object('id', pat.id,
    'uhid', pat.uhid,
    'name', CONCAT_WS(' ', NULLIF(pat.prefix,
    ''), pat.first_name, NULLIF(pat.middle_name,
    ''), pat.last_name),
    'gender', pat.gender,
    'date_of_birth', pat.date_of_birth),
    'recorded_by', vt.recorded_by,
    'recorded_at', vt.recorded_at,
    'is_retrospective', vt.is_retrospective,
    'temperature', vt.temperature,
    'pulse', vt.pulse,
    'pulse_rate', vt.pulse_rate,
    'systolic_bp', vt.systolic_bp,
    'diastolic_bp', vt.diastolic_bp,
    'bp_systolic', vt.bp_systolic,
    'bp_diastolic', vt.bp_diastolic,
    'respiratory_rate', vt.respiratory_rate,
    'spo2', vt.spo2,
    'weight_kg', vt.weight_kg,
    'height_cm', vt.height_cm,
    'bmi', vt.bmi,
    'head_circumference_cm', vt.head_circumference_cm,
    'pain_score', vt.pain_score,
    'consciousness', vt.consciousness,
    'oxygen_device', vt.oxygen_device,
    'oxygen_flow_lpm', vt.oxygen_flow_lpm,
    'fio2_percent', vt.fio2_percent,
    'capillary_refill_seconds', vt.capillary_refill_seconds,
    'respiratory_distress', vt.respiratory_distress,
    'notes', vt.notes)
FROM vitals vt
LEFT JOIN encounters e ON e.tenant_id = vt.tenant_id AND e.id = vt.encounter_id
JOIN patients pat ON pat.tenant_id = vt.tenant_id AND pat.id = COALESCE(vt.patient_id, e.patient_id)
WHERE vt.tenant_id = $1 AND vt.id = $2 AND vt.deleted_at IS NULL
