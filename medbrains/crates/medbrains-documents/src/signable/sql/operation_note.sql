-- Signable payload: operation_note. Binds $1 tenant, $2 record; authorship is checked apart (signable.rs).
SELECT jsonb_build_object('schema',
    'medbrains.signable.operation_note.v2',
    'record_type',
    'operation_note',
    'record_id', cr.id,
    'tenant_id', cr.tenant_id,
    'booking_id', cr.booking_id,
    'booking', jsonb_build_object('id', b.id,
    'patient_id', b.patient_id,
    'admission_id', b.admission_id,
    'procedure_name', b.procedure_name,
    'procedure_code', b.procedure_code,
    'laterality', b.laterality,
    'surgical_site', b.surgical_site,
    'scheduled_date', b.scheduled_date),
    'patient_id', b.patient_id,
    'patient', jsonb_build_object('id', pat.id,
    'uhid', pat.uhid,
    'name', CONCAT_WS(' ', NULLIF(pat.prefix,
    ''), pat.first_name, NULLIF(pat.middle_name,
    ''), pat.last_name),
    'gender', pat.gender,
    'date_of_birth', pat.date_of_birth),
    'surgeon_id', cr.surgeon_id,
    'patient_in_time', cr.patient_in_time,
    'patient_out_time', cr.patient_out_time,
    'incision_time', cr.incision_time,
    'closure_time', cr.closure_time,
    'procedure_performed', cr.procedure_performed,
    'findings', cr.findings,
    'technique', cr.technique,
    'complications', cr.complications,
    'blood_loss_ml', cr.blood_loss_ml,
    'specimens', cr.specimens,
    'implants', cr.implants,
    'drains', cr.drains,
    'instrument_count_correct_before', cr.instrument_count_correct_before,
    'instrument_count_correct_after', cr.instrument_count_correct_after,
    'sponge_count_correct', cr.sponge_count_correct,
    'count_discrepancy_action', cr.count_discrepancy_action,
    'notes', cr.notes)
FROM ot_case_records cr
JOIN ot_bookings b ON b.tenant_id = cr.tenant_id AND b.id = cr.booking_id
JOIN patients pat ON pat.tenant_id = b.tenant_id AND pat.id = b.patient_id
WHERE cr.tenant_id = $1 AND cr.id = $2 AND cr.deleted_at IS NULL
