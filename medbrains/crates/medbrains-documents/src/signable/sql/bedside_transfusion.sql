-- Signable payload: bedside_transfusion. Binds $1 tenant, $2 record, $3 signer role, $4 signer.
SELECT jsonb_build_object('schema',
    'medbrains.signable.bedside_transfusion.v2',
    'record_type',
    'bedside_transfusion',
    'record_id', t.id,
    'tenant_id', t.tenant_id,
    'admission_id', t.admission_id,
    'admission', jsonb_build_object('id', a.id,
    'encounter_id', a.encounter_id,
    'patient_id', a.patient_id,
    'admitting_doctor', a.admitting_doctor,
    'admitted_at', a.admitted_at),
    'patient_id', a.patient_id,
    'patient', jsonb_build_object('id', pat.id,
    'uhid', pat.uhid,
    'name', CONCAT_WS(' ', NULLIF(pat.prefix,
    ''), pat.first_name, NULLIF(pat.middle_name,
    ''), pat.last_name),
    'gender', pat.gender,
    'date_of_birth', pat.date_of_birth),
    'transfusion_date', t.transfusion_date,
    'product_type', t.product_type,
    'bag_number', t.bag_number,
    'blood_group', t.blood_group,
    'rh_factor', t.rh_factor,
    'volume_ml', t.volume_ml,
    'expiry_date', t.expiry_date,
    'crossmatch_compatible', t.crossmatch_compatible,
    'patient_verified_by_id', t.patient_verified_by_id,
    'product_verified_by_id', t.product_verified_by_id,
    'consent_on_file', t.consent_on_file,
    'wristband_uhid', t.wristband_uhid,
    'transfusion_start_time', t.transfusion_start_time,
    'started_by_id', t.started_by_id,
    'transfusion_end_time', t.transfusion_end_time,
    'total_volume_infused_ml', t.total_volume_infused_ml,
    'adverse_reaction', t.adverse_reaction,
    'reaction_type', t.reaction_type,
    'reaction_time', t.reaction_time,
    'action_taken', t.action_taken,
    'completed_by_id', t.completed_by_id)
FROM transfusions t
JOIN admissions a ON a.tenant_id = t.tenant_id AND a.id = t.admission_id
JOIN patients pat ON pat.tenant_id = a.tenant_id AND pat.id = a.patient_id
WHERE t.tenant_id = $1 AND t.id = $2 AND t.deleted_at IS NULL
AND ($3 <> 'primary' OR t.started_by_id = $4 OR t.completed_by_id = $4)
