-- Signable payload: er_triage. Binds $1 tenant, $2 record; authorship is checked apart (signable.rs).
SELECT jsonb_build_object('schema',
    'medbrains.signable.er_triage.v2',
    'record_type',
    'er_triage',
    'record_id', t.id,
    'tenant_id', t.tenant_id,
    'er_visit_id', t.er_visit_id,
    'er_visit', jsonb_build_object('id', v.id,
    'patient_id', v.patient_id,
    'encounter_id', v.encounter_id,
    'visit_number', v.visit_number,
    'arrival_time', v.arrival_time),
    'patient_id', v.patient_id,
    'patient', jsonb_build_object('id', pat.id,
    'uhid', pat.uhid,
    'name', CONCAT_WS(' ', NULLIF(pat.prefix,
    ''), pat.first_name, NULLIF(pat.middle_name,
    ''), pat.last_name),
    'gender', pat.gender,
    'date_of_birth', pat.date_of_birth),
    'triage_level', t.triage_level,
    'triage_system', t.triage_system,
    'score', t.score,
    'respiratory_rate', t.respiratory_rate,
    'pulse_rate', t.pulse_rate,
    'blood_pressure_systolic', t.blood_pressure_systolic,
    'blood_pressure_diastolic', t.blood_pressure_diastolic,
    'spo2', t.spo2,
    'gcs', jsonb_build_object('score', t.gcs_score,
    'eye', t.gcs_eye,
    'verbal', t.gcs_verbal,
    'motor', t.gcs_motor),
    'pain_score', t.pain_score,
    'chief_complaint', t.chief_complaint,
    'presenting_symptoms', t.presenting_symptoms,
    'allergies', t.allergies,
    'is_pregnant', t.is_pregnant,
    'disability_assessment', t.disability_assessment,
    'notes', t.notes,
    'assessed_by', t.assessed_by,
    'assessed_at', t.assessed_at)
FROM er_triage_assessments t
JOIN er_visits v ON v.tenant_id = t.tenant_id AND v.id = t.er_visit_id
JOIN patients pat ON pat.tenant_id = v.tenant_id AND pat.id = v.patient_id
WHERE t.tenant_id = $1 AND t.id = $2 AND t.deleted_at IS NULL
