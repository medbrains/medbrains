-- Signable payload: medication_administration. Binds $1 tenant, $2 record; authorship is checked apart (signable.rs).
SELECT jsonb_build_object('schema',
    'medbrains.signable.medication_administration.v2',
    'record_type',
    'medication_administration',
    'record_id', m.id,
    'tenant_id', m.tenant_id,
    'admission_id', m.admission_id,
    'admission', jsonb_build_object('id', a.id,
    'encounter_id', a.encounter_id,
    'patient_id', a.patient_id,
    'admitting_doctor', a.admitting_doctor,
    'admitted_at', a.admitted_at),
    'patient_id', a.patient_id,
    'patient', jsonb_build_object('id', pat.id,
    'uhid', pat.uhid,
    'name', CONCAT_WS(' ', NULLIF(pat.prefix,
    ''), pat.first_name, NULLIF(pat.middle_name,
    ''), pat.last_name),
    'gender', pat.gender,
    'date_of_birth', pat.date_of_birth),
    'prescription_item_id', m.prescription_item_id,
    'drug_name', m.drug_name,
    'dose', m.dose,
    'route', m.route,
    'frequency', m.frequency,
    'scheduled_at', m.scheduled_at,
    'administered_at', m.administered_at,
    'status', m.status,
    'administered_by', m.administered_by,
    'witnessed_by', m.witnessed_by,
    'double_checked_by', m.double_checked_by,
    'barcode_verified', m.barcode_verified,
    'is_high_alert', m.is_high_alert,
    'hold_reason', m.hold_reason,
    'refused_reason', m.refused_reason,
    'prn_reason', m.prn_reason,
    'missed_reason', m.missed_reason,
    'batch_number', m.batch_number,
    'batch_expiry', m.batch_expiry,
    'notes', m.notes)
FROM ipd_medication_administration m
JOIN admissions a ON a.tenant_id = m.tenant_id AND a.id = m.admission_id
JOIN patients pat ON pat.tenant_id = a.tenant_id AND pat.id = a.patient_id
WHERE m.tenant_id = $1 AND m.id = $2 AND m.deleted_at IS NULL
