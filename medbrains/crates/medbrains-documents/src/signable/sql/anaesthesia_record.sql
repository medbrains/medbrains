-- Signable payload: anaesthesia_record. Binds $1 tenant, $2 record, $3 signer role, $4 signer.
SELECT jsonb_build_object('schema',
    'medbrains.signable.anaesthesia_record.v2',
    'record_type',
    'anaesthesia_record',
    'record_id', ar.id,
    'tenant_id', ar.tenant_id,
    'booking_id', ar.booking_id,
    'booking', jsonb_build_object('id', b.id,
    'patient_id', b.patient_id,
    'admission_id', b.admission_id,
    'procedure_name', b.procedure_name,
    'procedure_code', b.procedure_code,
    'laterality', b.laterality,
    'surgical_site', b.surgical_site,
    'scheduled_date', b.scheduled_date),
    'patient_id', b.patient_id,
    'patient', jsonb_build_object('id', pat.id,
    'uhid', pat.uhid,
    'name', CONCAT_WS(' ', NULLIF(pat.prefix,
    ''), pat.first_name, NULLIF(pat.middle_name,
    ''), pat.last_name),
    'gender', pat.gender,
    'date_of_birth', pat.date_of_birth),
    'anesthetist_id', ar.anesthetist_id,
    'anesthesia_type', ar.anesthesia_type,
    'asa_class', ar.asa_class,
    'induction_time', ar.induction_time,
    'intubation_time', ar.intubation_time,
    'extubation_time', ar.extubation_time,
    'airway_details', ar.airway_details,
    'drugs_administered', ar.drugs_administered,
    'monitoring_events', ar.monitoring_events,
    'fluids_given', ar.fluids_given,
    'blood_products', ar.blood_products,
    'adverse_events', ar.adverse_events,
    'complications', ar.complications,
    'fasting_override_reason', ar.fasting_override_reason,
    'notes', ar.notes)
FROM ot_anesthesia_records ar
JOIN ot_bookings b ON b.tenant_id = ar.tenant_id AND b.id = ar.booking_id
JOIN patients pat ON pat.tenant_id = b.tenant_id AND pat.id = b.patient_id
WHERE ar.tenant_id = $1 AND ar.id = $2 AND ar.deleted_at IS NULL
AND ($3 <> 'primary' OR ar.anesthetist_id = $4 OR b.anesthetist_id = $4 OR b.anesthesiologist_id = $4)
