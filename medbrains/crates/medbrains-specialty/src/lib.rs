//! Specialty departments leaf crate: psychiatry, maternity, dental, ophthalmology,
//! long-term care. Mounted via router().

use axum::{
    Router,
    routing::{get, post, put},
};
use medbrains_server_core::state::AppState;

pub mod long_term_care;
pub mod ophtho_print;
pub mod ophtho_refraction;
pub mod psych_admissions;
pub mod psych_board;
pub mod psych_challenges;
pub mod psych_legal;
pub mod psych_mhca;
pub mod psych_screenings;
pub mod specialty_dental;
pub mod specialty_dental_perio;
pub mod specialty_dental_plan;
pub mod specialty_maternity;
pub mod specialty_ophtho;
pub mod specialty_psychiatry;

pub fn router() -> Router<AppState> {
    Router::new()
        .route(
            "/api/ltc/mds",
            get(long_term_care::list_mds_assessments).post(long_term_care::create_mds_assessment),
        )
        .route(
            "/api/ltc/mds/{id}/complete",
            post(long_term_care::complete_mds_assessment),
        )
        .route(
            "/api/ltc/medications",
            get(long_term_care::list_ltc_medications).post(long_term_care::add_ltc_medication),
        )
        .route(
            "/api/ltc/medications/{id}/refill",
            post(long_term_care::refill_ltc_medication),
        )
        .route(
            "/api/ltc/medications/{id}",
            put(long_term_care::update_ltc_medication),
        )
        .route(
            "/api/ltc/rehab",
            get(long_term_care::list_rehab_progress).post(long_term_care::add_rehab_progress),
        )
        .route(
            "/api/ltc/family-messages",
            get(long_term_care::list_family_messages).post(long_term_care::post_family_message),
        )
        .route(
            "/api/ltc/family-messages/{id}",
            put(long_term_care::update_family_message),
        )
        .route(
            "/api/ltc/readmission-risk",
            get(long_term_care::list_readmission_risk)
                .post(long_term_care::assess_readmission_risk),
        )
        .route(
            "/api/ltc/referrals",
            get(long_term_care::list_home_care_referrals)
                .post(long_term_care::create_home_care_referral),
        )
        .route(
            "/api/ltc/referrals/{id}",
            put(long_term_care::update_home_care_referral),
        )
        .route(
            "/api/ltc/snf-admissions",
            get(long_term_care::list_snf_admissions).post(long_term_care::create_snf_admission),
        )
        .route(
            "/api/ltc/snf-admissions/{id}",
            put(long_term_care::update_snf_admission),
        )
        .route(
            "/api/specialty/ophthalmology/exams",
            get(specialty_ophtho::list_ophtho_exams).post(specialty_ophtho::create_ophtho_exam),
        )
        .route(
            "/api/specialty/ophthalmology/exams/{id}",
            get(specialty_ophtho::get_ophtho_exam).put(specialty_ophtho::update_ophtho_exam),
        )
        .route(
            "/api/specialty/ophthalmology/exams/{id}/sign",
            post(specialty_ophtho::sign_ophtho_exam),
        )
        .route(
            "/api/specialty/dental/exams",
            get(specialty_dental::list_dental_exams).post(specialty_dental::create_dental_exam),
        )
        .route(
            "/api/specialty/dental/exams/{id}",
            get(specialty_dental::get_dental_exam).put(specialty_dental::update_dental_exam),
        )
        .route(
            "/api/specialty/dental/exams/{exam_id}/chart",
            get(specialty_dental::list_chart_entries).post(specialty_dental::create_chart_entry),
        )
        .route(
            "/api/specialty/dental/exams/{exam_id}/perio",
            post(specialty_dental_perio::record_perio_chart),
        )
        .route(
            "/api/specialty/dental/patients/{patient_id}/perio",
            get(specialty_dental_perio::patient_perio_history),
        )
        .route(
            "/api/specialty/dental/chart/{id}",
            put(specialty_dental_plan::update_chart_entry)
                .delete(specialty_dental_plan::remove_chart_entry),
        )
        .route(
            "/api/specialty/dental/exams/{exam_id}/treatment",
            get(specialty_dental_plan::list_treatment).post(specialty_dental_plan::plan_treatment),
        )
        .route(
            "/api/specialty/dental/treatment/{id}/complete",
            post(specialty_dental_plan::complete_treatment),
        )
        .route(
            "/api/specialty/dental/treatment/{id}/cancel",
            post(specialty_dental_plan::cancel_treatment),
        )
        .route(
            "/api/specialty/psychiatry/patients",
            get(specialty_psychiatry::list_psych_patients)
                .post(specialty_psychiatry::create_psych_patient),
        )
        .route(
            "/api/specialty/psychiatry/patients/{id}",
            get(specialty_psychiatry::get_psych_patient)
                .put(specialty_psychiatry::update_psych_patient),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/assessments",
            get(specialty_psychiatry::list_assessments)
                .post(specialty_psychiatry::create_assessment),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/ect",
            get(specialty_psychiatry::list_ect_sessions)
                .post(specialty_psychiatry::create_ect_session),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/restraints",
            get(specialty_psychiatry::list_restraints).post(specialty_psychiatry::create_restraint),
        )
        .route(
            "/api/specialty/psychiatry/restraints/{id}/release",
            put(specialty_psychiatry::release_restraint),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/mhrb",
            get(specialty_psychiatry::list_mhrb_notifications)
                .post(specialty_psychiatry::create_mhrb_notification),
        )
        .route(
            "/api/specialty/psychiatry/mhrb/{id}",
            put(specialty_psychiatry::update_mhrb_notification),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/counseling",
            get(specialty_psychiatry::list_counseling_sessions)
                .post(specialty_psychiatry::create_counseling_session),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/admissions",
            get(psych_admissions::list_admissions).post(psych_admissions::create_admission),
        )
        .route(
            "/api/specialty/psychiatry/admissions/{id}/discharge",
            post(psych_admissions::discharge_admission),
        )
        .route(
            "/api/specialty/psychiatry/admissions/{id}/board-report",
            post(psych_admissions::report_admission_to_board),
        )
        .route(
            "/api/specialty/psychiatry/admissions/{id}/board-decision",
            post(psych_admissions::record_board_decision),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/nominated-representatives",
            get(psych_legal::list_representatives).post(psych_legal::create_representative),
        )
        .route(
            "/api/specialty/psychiatry/nominated-representatives/{id}/revoke",
            post(psych_legal::revoke_representative),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/advance-directives",
            get(psych_legal::list_directives).post(psych_legal::create_directive),
        )
        .route(
            "/api/specialty/psychiatry/advance-directives/{id}/revoke",
            post(psych_legal::revoke_directive),
        )
        .route(
            "/api/specialty/psychiatry/advance-directives/{id}/challenges",
            post(psych_challenges::create_challenge),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/directive-challenges",
            get(psych_challenges::list_challenges),
        )
        .route(
            "/api/specialty/psychiatry/directive-challenges/{id}/decision",
            post(psych_challenges::decide_challenge),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/screenings",
            get(psych_screenings::list_screenings).post(psych_screenings::create_screening),
        )
        .route(
            "/api/specialty/psychiatry/screenings/{id}/safety-review",
            post(psych_screenings::complete_safety_review),
        )
        .route(
            "/api/specialty/psychiatry/safety-reviews/pending",
            get(psych_screenings::list_pending_safety_reviews),
        )
        .route(
            "/api/specialty/psychiatry/restraints/{id}/nominated-rep-informed",
            post(psych_board::mark_nominated_rep_informed),
        )
        .route(
            "/api/specialty/psychiatry/restraint-report",
            get(psych_board::restraint_monthly_report),
        )
        .route(
            "/api/specialty/psychiatry/patients/{patient_id}/abdm-consent",
            put(psych_board::set_abdm_consent),
        )
        .route(
            "/api/specialty/maternity/registrations",
            get(specialty_maternity::list_registrations)
                .post(specialty_maternity::create_registration),
        )
        .route(
            "/api/specialty/maternity/registrations/{id}",
            get(specialty_maternity::get_registration),
        )
        .route(
            "/api/specialty/maternity/registrations/{registration_id}/anc",
            get(specialty_maternity::list_anc_visits).post(specialty_maternity::create_anc_visit),
        )
        .route(
            "/api/specialty/maternity/registrations/{registration_id}/labor",
            get(specialty_maternity::list_labor_records)
                .post(specialty_maternity::create_labor_record),
        )
        .route(
            "/api/specialty/maternity/labor/{id}",
            put(specialty_maternity::update_labor_record),
        )
        .route(
            "/api/specialty/maternity/labor/{labor_id}/newborns",
            get(specialty_maternity::list_newborns).post(specialty_maternity::create_newborn),
        )
        .route(
            "/api/specialty/maternity/newborns/{newborn_id}/verify-identity",
            post(specialty_maternity::verify_newborn_identity),
        )
        .route(
            "/api/specialty/maternity/registrations/{registration_id}/postnatal",
            get(specialty_maternity::list_postnatal).post(specialty_maternity::create_postnatal),
        )
}
